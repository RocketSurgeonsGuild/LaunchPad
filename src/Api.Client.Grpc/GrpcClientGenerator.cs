using Microsoft.CodeAnalysis;

namespace Rocket.Surgery.LaunchPad.Api.Generators;

/// <summary>
///     Generates a code-first gRPC client (protobuf-net.Grpc) for every <c>*GrpcClient</c> operation host: the same <c>[Service]</c> contract the
///     server generator writes, typed methods named after the operations, one mediator handler per operation and an <c>Add{Host}()</c> that
///     registers it all through protobuf-net.Grpc's client factory.
/// </summary>
[Generator]
public sealed class GrpcClientGenerator : IIncrementalGenerator
{
    private const string Ct = "cancellationToken";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static output => HostPipeline.EmitMarker(output, HostKind.GrpcClient));
        var hosts = HostPipeline.Hosts(context, HostKind.GrpcClient);
        var assemblyName = context.CompilationProvider.Select(static (c, _) => c.AssemblyName ?? "Assembly");
        var mediatorGenerators = context.AnalyzerConfigOptionsProvider.Select(static (options, _) => HostPipeline.MediatorGenerators(options.GlobalOptions));
        context.RegisterSourceOutput(
            hosts.Combine(assemblyName).Combine(mediatorGenerators),
            static (output, pair) => Emit(output, pair.Left.Left, pair.Left.Right, pair.Right)
        );
    }

    private static void Emit(SourceProductionContext output, EquatableArray<HostModel> hosts, string assemblyName, EquatableArray<string>? mediatorGenerators)
    {
        foreach (var host in hosts)
        {
            foreach (var diagnostic in host.Diagnostics) output.ReportDiagnostic(diagnostic.ToDiagnostic());
            if (host.Profile is not { } profile) continue;
            ClientEmit.ReportHostChecks(output, host, profile, mediatorGenerators);
            output.AddSource(host.FullyQualifiedName.Replace("global::", "") + ".GrpcClient.g.cs", Write(host, profile, output));
        }

        ClientEmit.EmitShared(output, hosts, assemblyName);
    }

    private static string Write(HostModel host, ProfileModel profile, SourceProductionContext output)
    {
        var version = typeof(GrpcClientGenerator).Assembly.GetName().Version;
        var contract = GrpcEmit.ContractName(host);
        var w = new SourceWriter();
        w.Line("// <auto-generated/>").Line("#nullable enable").Line("#pragma warning disable CS1591").Line();
        if (host.Namespace is { } ns) w.Open($"namespace {ns}");

        GrpcEmit.WriteContract(w, host, host.Operations, version);
        w.Line();
        w.Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"Rocket.Surgery.LaunchPad.Api.Client.Grpc\", \"{version}\")]");
        w.Open($"{host.Accessibility} partial class {host.Name}");
        w.Line($"private readonly {contract} __contract;");
        w.Line();
        w.Line($"/// <summary>Creates the client. Register it with <c>services.Add{host.Name}()</c>.</summary>");
        w.Open($"public {host.Name}({contract} contract)");
        w.Line("global::System.ArgumentNullException.ThrowIfNull(contract);");
        w.Line("__contract = contract;");
        w.Close();
        w.Line();
        GrpcEmit.WriteModelConfiguration(w, host.Operations);

        foreach (var operation in host.Operations)
        {
            w.Line();
            WriteMethod(w, host, operation);
        }

        var handled = ClientEmit.WriteHandlers(w, host, profile, output);
        w.Close();
        w.Line();

        w.Line($"/// <summary>Registers <see cref=\"{host.Name}\" />{( handled.Length > 0 ? " and its mediator handlers" : "" )}.</summary>");
        w.Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"Rocket.Surgery.LaunchPad.Api.Client.Grpc\", \"{version}\")]");
        w.Open($"{host.Accessibility} static class {host.Name}ServiceCollectionExtensions");
        w.Line($"/// <summary>Registers <see cref=\"{host.Name}\" />, its gRPC client and one mediator handler per operation.</summary>");
        w.Line("/// <param name=\"services\">The services.</param>");
        w.Line("/// <param name=\"configure\">Sets the address and other client factory options.</param>");
        w.Line("/// <returns>The HttpClient builder behind the gRPC channel, for handlers and resilience.</returns>");
        w.Open(
            $"public static global::Microsoft.Extensions.DependencyInjection.IHttpClientBuilder Add{host.Name}(this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services, global::System.Action<global::Grpc.Net.ClientFactory.GrpcClientFactoryOptions>? configure = null)"
        );
        w.Line("global::System.ArgumentNullException.ThrowIfNull(services);");
        ClientEmit.WriteRegistrations(w, host, profile, handled);
        w.Line($"{host.Name}.ConfigureGrpcModel();");
        w.Line(
            $"return configure is null ? global::ProtoBuf.Grpc.ClientFactory.ServicesExtensions.AddCodeFirstGrpcClient<{contract}>(services) : global::ProtoBuf.Grpc.ClientFactory.ServicesExtensions.AddCodeFirstGrpcClient<{contract}>(services, configure);"
        );
        w.Close();
        w.Close();
        if (host.Namespace is { }) w.Close();
        return w.ToString();
    }

    private static void WriteMethod(SourceWriter w, HostModel host, OperationModel operation)
    {
        var parameter = operation.WireType;
        w.Line($"/// <summary>Sends <see cref=\"{ClientEmit.Cref(operation.RequestType)}\" /> to the <c>{operation.Name}</c> operation.</summary>");
        var signature = operation.Kind switch
        {
            RequestKind.Stream =>
                $"public async global::System.Collections.Generic.IAsyncEnumerable<{operation.ResponseType}> {operation.Name}({parameter} request, [global::System.Runtime.CompilerServices.EnumeratorCancellation] global::System.Threading.CancellationToken {Ct} = default)",
            RequestKind.Void => $"public async global::System.Threading.Tasks.Task {operation.Name}({parameter} request, global::System.Threading.CancellationToken {Ct} = default)",
            RequestKind.Unary or RequestKind.Infer =>
                $"public async global::System.Threading.Tasks.Task<{operation.ResponseType}> {operation.Name}({parameter} request, global::System.Threading.CancellationToken {Ct} = default)",
            _ => throw new ArgumentOutOfRangeException(nameof(operation)),
        };
        w.Open(signature);
        w.Line("global::System.ArgumentNullException.ThrowIfNull(request);");
        w.Line($"var __options = new global::Grpc.Core.CallOptions(cancellationToken: {Ct});");
        w.Line($"Configure{operation.Name}(ref __options);");
        var argument = operation.RequestIsMessage ? "request" : $"new {GrpcEmit.WireRequest(host, operation)}(request)";
        var call = $"__contract.{operation.Name}({argument}, __options)";
        var unwrap = operation.ResponseIsMessage ? "" : ".Value";
        switch (operation.Kind)
        {
            case RequestKind.Stream:
                w.Line($"await foreach (var __item in global::System.Threading.Tasks.TaskAsyncEnumerableExtensions.WithCancellation({call}, {Ct}).ConfigureAwait(false)) yield return __item{unwrap};");
                break;
            case RequestKind.Void:
                w.Line($"await {call}.ConfigureAwait(false);");
                break;
            case RequestKind.Unary:
            case RequestKind.Infer:
            default:
                if (operation.ResponseNullable)
                {
                    // The server answers a null response with NotFound.
                    w.Open("try");
                    w.Line($"return (await {call}.ConfigureAwait(false)){unwrap};");
                    w.Close();
                    w.Open("catch (global::Grpc.Core.RpcException __exception) when (__exception.StatusCode == global::Grpc.Core.StatusCode.NotFound)");
                    w.Line("return default;");
                    w.Close();
                }
                else
                {
                    w.Line($"return (await {call}.ConfigureAwait(false)){unwrap};");
                }

                break;
        }

        w.Close();
        w.Line();
        w.Line($"/// <summary>Adjusts the call options (headers, deadline, credentials) for <c>{operation.Name}</c>. Implement it in your part of the host.</summary>");
        w.Line($"partial void Configure{operation.Name}(ref global::Grpc.Core.CallOptions options);");
    }
}

using Microsoft.CodeAnalysis;

namespace Rocket.Surgery.LaunchPad.Api.Generators;

/// <summary>
///     Generates a code-first gRPC service (protobuf-net.Grpc) for every <c>*Service</c> operation host: a <c>[Service]</c> contract interface
///     with one method per operation, the host's implementation of it through the mediator, and <c>Map{Host}()</c>.
/// </summary>
/// <remarks>
///     The gRPC client generator writes the same contract from a client host, so client and server agree on the wire through the service name
///     (the group) and the operation names alone; the contracts project needs no gRPC reference.
/// </remarks>
[Generator]
public sealed class GrpcServiceGenerator : IIncrementalGenerator
{
    private const string Ct = "__cancellationToken";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(static output => HostPipeline.EmitMarker(output, HostKind.GrpcService));
        var hosts = HostPipeline.Hosts(context, HostKind.GrpcService);
        context.RegisterSourceOutput(hosts, static (output, models) => Emit(output, models));
    }

    private static void Emit(SourceProductionContext output, EquatableArray<HostModel> hosts)
    {
        foreach (var host in hosts)
        {
            foreach (var diagnostic in host.Diagnostics) output.ReportDiagnostic(diagnostic.ToDiagnostic());
            if (host.Profile is null) continue;
            output.AddSource(host.FullyQualifiedName.Replace("global::", "") + ".Grpc.g.cs", Write(host, host.Profile, output));
        }
    }

    private static string Write(HostModel host, ProfileModel profile, SourceProductionContext output)
    {
        var operations = new List<(OperationModel Operation, string Service)>();
        foreach (var operation in host.Operations)
        {
            if (ServerDispatch.ServiceType(profile, operation) is { } service)
            {
                operations.Add((operation, service));
                continue;
            }

            output.ReportDiagnostic(
                DiagnosticInfo.Create(ApiDiagnostics.FeatureSkipped, operation.Location, operation.Name, host.Name, $"the {profile.Name} profile cannot dispatch {ServerEmit.KindName(operation.Kind)} operations")
                              .ToDiagnostic()
            );
        }

        var w = new SourceWriter();
        w.Line("// <auto-generated/>").Line("#nullable enable").Line("#pragma warning disable CS1591").Line();
        if (host.Namespace is { } ns) w.Open($"namespace {ns}");

        var contract = GrpcEmit.ContractName(host);
        GrpcEmit.WriteContract(w, host, operations.Select(o => o.Operation), typeof(GrpcServiceGenerator).Assembly.GetName().Version);
        w.Line();

        w.Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"Rocket.Surgery.LaunchPad.Api.Grpc\", \"{typeof(GrpcServiceGenerator).Assembly.GetName().Version}\")]");
        w.Open($"{host.Accessibility} partial class {host.Name} : {contract}");
        GrpcEmit.WriteModelConfiguration(w, operations.Select(o => o.Operation));
        var first = false;
        foreach (var (operation, service) in operations)
        {
            if (!first) w.Line();
            first = false;
            WriteMethod(w, host, profile, operation, service);
        }

        w.Close();
        w.Line();
        w.Line($"/// <summary>Maps <see cref=\"{host.Name}\" />. Register code-first gRPC with <c>services.AddCodeFirstGrpc()</c>.</summary>");
        w.Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"Rocket.Surgery.LaunchPad.Api.Grpc\", \"{typeof(GrpcServiceGenerator).Assembly.GetName().Version}\")]");
        w.Open($"{host.Accessibility} static class {host.Name}EndpointRouteBuilderExtensions");
        w.Line(
            $"public static global::Microsoft.AspNetCore.Builder.GrpcServiceEndpointConventionBuilder Map{host.Name}(this global::Microsoft.AspNetCore.Routing.IEndpointRouteBuilder endpoints)"
        );
        w.Open("");
        w.Line($"{host.Name}.ConfigureGrpcModel();");
        w.Line($"return global::Microsoft.AspNetCore.Builder.GrpcEndpointRouteBuilderExtensions.MapGrpcService<{host.Name}>(endpoints);");
        w.Close();
        w.Close();
        if (host.Namespace is { }) w.Close();
        return w.ToString();
    }

    private static void WriteMethod(SourceWriter w, HostModel host, ProfileModel profile, OperationModel operation, string service)
    {
        w.Line($"/// <summary>Sends <see cref=\"{ClientEmit.Cref(operation.RequestType)}\" /> through the mediator.</summary>");
        var call = ServerDispatch.Call(profile, operation, "__request", Ct);
        // A stream is relayed item by item when it has to be awaited first (Foundatio, Immediate.Handlers) or its items wrapped.
        var relay = operation.Kind == RequestKind.Stream && ( call.StartsWith("await ", StringComparison.Ordinal) || !operation.ResponseIsMessage );
        var isAsync = operation.Kind != RequestKind.Stream || relay;
        var (returnType, parameters) = GrpcEmit.Signature(host, operation, withDefault: false);
        w.Open($"public {( isAsync ? "async " : "" )}{returnType} {operation.Name}({parameters})");
        w.Line($"var {ServerDispatch.SenderParameter} = global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<{service}>(global::Grpc.Core.ServerCallContextExtensions.GetHttpContext(context.ServerCallContext!).RequestServices);");
        w.Line($"var {Ct} = context.CancellationToken;");
        var wire = operation.RequestIsMessage ? "request" : "request.Value";
        w.Line(operation.InputType is { } ? $"var __request = {wire}.Create();" : $"var __request = {wire};");
        switch (operation.Kind)
        {
            case RequestKind.Stream:
                if (relay)
                {
                    var item = operation.ResponseIsMessage ? "__item" : $"new {GrpcEmit.WireResponse(host, operation)}(__item)";
                    w.Line($"await foreach (var __item in global::System.Threading.Tasks.TaskAsyncEnumerableExtensions.WithCancellation({call}, {Ct}).ConfigureAwait(false)) yield return {item};");
                }
                else
                {
                    w.Line($"return {call};");
                }

                break;
            case RequestKind.Void:
                w.Line($"await {call}.ConfigureAwait(false);");
                break;
            case RequestKind.Unary:
            case RequestKind.Infer:
            default:
                w.Line($"var __response = await {call}.ConfigureAwait(false);");
                if (operation.ResponseNullable)
                {
                    w.Line(
                        $"if (__response is null) throw new global::Grpc.Core.RpcException(new global::Grpc.Core.Status(global::Grpc.Core.StatusCode.NotFound, {SourceWriter.Literal(operation.Name + " found nothing")}));"
                    );
                }

                var value = operation.ResponseIsNullableValueType ? "__response.Value" : "__response";
                w.Line(operation.ResponseIsMessage ? $"return {value};" : $"return new {GrpcEmit.WireResponse(host, operation)}({value});");
                break;
        }

        w.Close();
    }
}

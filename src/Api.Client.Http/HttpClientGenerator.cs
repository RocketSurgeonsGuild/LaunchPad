using Microsoft.CodeAnalysis;

namespace Rocket.Surgery.LaunchPad.Api.Generators;

/// <summary>
///     Generates an HTTP client for every client operation host: one method per listed operation, named after the operation, plus one mediator
///     handler per operation (the shape depends on the mediator profile) and an <c>Add{Host}()</c> registration that returns the
///     <c>IHttpClientBuilder</c>.
/// </summary>
[Generator]
public sealed class HttpClientGenerator : IIncrementalGenerator
{
    private const string Tasks = "global::System.Threading.Tasks";
    private const string Ct = "cancellationToken";
    // Each transport package emits its helpers into its own namespace, so a project can reference several of them.
    private const string Generated = "global::Rocket.Surgery.LaunchPad.Api.Generated.Http";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(
            static output =>
            {
                HostPipeline.EmitMarker(output, HostKind.HttpClient);
                output.AddSource("Rocket.Surgery.LaunchPad.Api.Generated.ClientHelpers.g.cs", ClientHelpers);
            }
        );

        var hosts = HostPipeline.Hosts(context, HostKind.HttpClient);
        var assemblyName = context.CompilationProvider.Select(static (c, _) => c.AssemblyName ?? "Assembly");
        var mediatorGenerators = context.AnalyzerConfigOptionsProvider.Select(static (options, _) => HostPipeline.MediatorGenerators(options.GlobalOptions));
        context.RegisterSourceOutput(
            hosts.Combine(assemblyName).Combine(mediatorGenerators),
            static (output, pair) => Emit(output, pair.Left.Left, pair.Left.Right, pair.Right)
        );
    }

    private static void Emit(SourceProductionContext output, EquatableArray<HostModel> hosts, string assemblyName, EquatableArray<string>? mediatorGenerators)
    {
        foreach (var host in hosts)
        {
            foreach (var diagnostic in host.Diagnostics) output.ReportDiagnostic(diagnostic.ToDiagnostic());
            if (host.Profile is not { } profile) continue;
            ClientEmit.ReportHostChecks(output, host, profile, mediatorGenerators);
            output.AddSource(host.FullyQualifiedName.Replace("global::", "") + ".HttpClient.g.cs", Write(host, profile, output));
        }

        ClientEmit.EmitShared(output, hosts, assemblyName);
    }

    private static string Write(HostModel host, ProfileModel profile, SourceProductionContext output)
    {
        var w = new SourceWriter();
        w.Line("// <auto-generated/>").Line("#nullable enable").Line("#pragma warning disable CS1591").Line();
        if (host.Namespace is { } ns) w.Open($"namespace {ns}");

        var version = typeof(HttpClientGenerator).Assembly.GetName().Version;
        w.Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"Rocket.Surgery.LaunchPad.Api.Client.Http\", \"{version}\")]");
        w.Open($"{host.Accessibility} partial class {host.Name}");
        w.Line($"/// <summary>The name of the <see cref=\"global::System.Net.Http.HttpClient\" /> this client sends through.</summary>");
        w.Line($"public const string HttpClientName = {SourceWriter.Literal(host.ClientName)};");
        w.Line();
        w.Line("private static readonly global::System.Text.Json.JsonSerializerOptions __jsonOptions = CreateJsonOptions();");
        w.Line("private readonly global::System.Net.Http.IHttpClientFactory __httpClientFactory;");
        w.Line();
        w.Line($"/// <summary>Creates the client. Register it with <c>services.Add{host.Name}()</c>.</summary>");
        w.Open($"public {host.Name}(global::System.Net.Http.IHttpClientFactory httpClientFactory)");
        w.Line("global::System.ArgumentNullException.ThrowIfNull(httpClientFactory);");
        w.Line("__httpClientFactory = httpClientFactory;");
        w.Close();
        w.Line();
        w.Open("private static global::System.Text.Json.JsonSerializerOptions CreateJsonOptions()");
        w.Line($"var options = new global::System.Text.Json.JsonSerializerOptions(global::System.Text.Json.JsonSerializerDefaults.{( host.JsonWebDefaults ? "Web" : "General" )});");
        w.Line("ConfigureJsonOptions(options);");
        w.Line("// Reflection-based metadata unless a JsonSerializerContext was supplied; native AOT apps add one in ConfigureJsonOptions.");
        w.Line("if (global::System.Text.Json.JsonSerializer.IsReflectionEnabledByDefault) options.TypeInfoResolver ??= ReflectionTypeInfoResolver();");
        w.Line("options.MakeReadOnly();");
        w.Line("return options;");
        w.Close();
        w.Line();
        // Only reached when reflection-based serialization is enabled; trimmed and native AOT apps disable it and supply a JsonSerializerContext.
        w.Line("[global::System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage(\"Trimming\", \"IL2026\", Justification = \"Only called when JsonSerializer.IsReflectionEnabledByDefault is true.\")]");
        w.Line("[global::System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage(\"AOT\", \"IL3050\", Justification = \"Only called when JsonSerializer.IsReflectionEnabledByDefault is true.\")]");
        w.Line("private static global::System.Text.Json.Serialization.Metadata.IJsonTypeInfoResolver? ReflectionTypeInfoResolver() => global::System.Text.Json.JsonSerializerOptions.Default.TypeInfoResolver;");
        w.Line();
        w.Line("/// <summary>Adjusts the JSON options, e.g. to insert a <c>JsonSerializerContext</c> for trimming and native AOT.</summary>");
        w.Line("static partial void ConfigureJsonOptions(global::System.Text.Json.JsonSerializerOptions options);");

        foreach (var operation in host.Operations)
        {
            w.Line();
            WriteMethod(w, host, operation);
        }

        var handled = ClientEmit.WriteHandlers(w, host, profile, output);

        w.Close();
        w.Line();
        WriteRegistration(w, host, profile, handled);
        if (host.Namespace is { }) w.Close();
        return w.ToString();
    }

    private static void WriteMethod(SourceWriter w, HostModel host, OperationModel operation)
    {
        var parameter = operation.InputType ?? operation.RequestType;
        var jsonType = operation.ResponseIsNullableValueType ? operation.ResponseType : operation.ResponseTypeNotNull;
        w.Line($"/// <summary>Sends <see cref=\"{ClientEmit.Cref(operation.RequestType)}\" /> to <c>{operation.Verb.ToString().ToUpperInvariant()} /{RouteText.Join(host.BaseRoute, operation.Route)}</c>.</summary>");
        var signature = operation.Kind switch
        {
            RequestKind.Stream => $"public async global::System.Collections.Generic.IAsyncEnumerable<{operation.ResponseType}> {operation.Name}({parameter} request, [global::System.Runtime.CompilerServices.EnumeratorCancellation] global::System.Threading.CancellationToken {Ct} = default)",
            RequestKind.Void => $"public async {Tasks}.Task {operation.Name}({parameter} request, global::System.Threading.CancellationToken {Ct} = default)",
            RequestKind.Unary or RequestKind.Infer => $"public async {Tasks}.Task<{operation.ResponseType}> {operation.Name}({parameter} request, global::System.Threading.CancellationToken {Ct} = default)",
            _ => throw new ArgumentOutOfRangeException(nameof(operation)),
        };
        w.Open(signature);
        w.Line("global::System.ArgumentNullException.ThrowIfNull(request);");
        w.Line($"var __url = {Url(host, operation)};");
        var query = operation.HasBody ? [] : operation.Members.Where(m => m.Source == BindingSource.Query).ToArray();
        var version = operation.Version ?? host.Version;
        if (query.Length > 0 || version is { })
        {
            w.Line($"var __query = new {Generated}.ApiQuery();");
            foreach (var member in query) w.Line($"__query.Add({SourceWriter.Literal(member.WireName)}, request.{member.Name});");
            if (version is { }) w.Line($"__query.Add(\"api-version\", {SourceWriter.Literal(version)});");
            w.Line("__url += __query.ToString();");
        }

        w.Line($"using var __message = new global::System.Net.Http.HttpRequestMessage(new global::System.Net.Http.HttpMethod({SourceWriter.Literal(operation.Verb.ToString().ToUpperInvariant())}), __url);");
        foreach (var header in operation.Members.Where(m => m.Source == BindingSource.Header))
        {
            w.Line($"if (request.{header.Name} is {{ }} __{header.Name}) __message.Headers.TryAddWithoutValidation({SourceWriter.Literal(header.WireName)}, {Generated}.ApiFormat.Value(__{header.Name}));");
        }

        if (operation.HasBody)
        {
            w.Line($"__message.Content = global::System.Net.Http.Json.JsonContent.Create(request, (global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<{parameter}>)__jsonOptions.GetTypeInfo(typeof({parameter})));");
        }

        w.Line($"Configure{operation.Name}(__message);");
        var completion = operation.Kind == RequestKind.Stream ? "global::System.Net.Http.HttpCompletionOption.ResponseHeadersRead" : "global::System.Net.Http.HttpCompletionOption.ResponseContentRead";
        w.Line($"using var __response = await __httpClientFactory.CreateClient(HttpClientName).SendAsync(__message, {completion}, {Ct}).ConfigureAwait(false);");
        if (operation.ResponseNullable && operation.Kind == RequestKind.Unary)
        {
            w.Line("if (__response.StatusCode == global::System.Net.HttpStatusCode.NotFound) return default;");
        }

        w.Line($"await {Generated}.ApiClientResponse.EnsureSuccessAsync(__response, {Ct}).ConfigureAwait(false);");
        switch (operation.Kind)
        {
            case RequestKind.Void:
                break;
            case RequestKind.Stream:
                w.Line($"var __typeInfo = (global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<{jsonType}>)__jsonOptions.GetTypeInfo(typeof({jsonType}));");
                w.Line($"await foreach (var __item in global::System.Threading.Tasks.TaskAsyncEnumerableExtensions.ConfigureAwait({Generated}.ApiClientResponse.ReadNdjsonAsync(__response, __typeInfo, {Ct}), false)) yield return __item;");
                break;
            case RequestKind.Unary:
            case RequestKind.Infer:
            default:
                w.Line($"var __typeInfo = (global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<{jsonType}>)__jsonOptions.GetTypeInfo(typeof({jsonType}));");
                w.Line($"return (await global::System.Net.Http.Json.HttpContentJsonExtensions.ReadFromJsonAsync(__response.Content, __typeInfo, {Ct}).ConfigureAwait(false))!;");
                break;
        }

        w.Close();
        w.Line();
        w.Line($"/// <summary>Adjusts the request for <c>{operation.Name}</c> before it is sent. Implement it in your part of <see cref=\"{host.Name}\" />.</summary>");
        w.Line($"partial void Configure{operation.Name}(global::System.Net.Http.HttpRequestMessage request);");
    }

    // The URL relative to the client's BaseAddress, with every route value escaped.
    private static string Url(HostModel host, OperationModel operation)
    {
        var path = RouteText.Join(host.BaseRoute, operation.Route);
        var parts = new List<string>();
        var position = 0;
        while (path.IndexOf('{', position) is var start and >= 0)
        {
            var end = path.IndexOf('}', start);
            var token = RouteText.Tokens(path.Substring(start, end - start + 1)).First();
            var member = operation.Members.First(m => m.Source == BindingSource.Route && string.Equals(m.WireName, token, StringComparison.OrdinalIgnoreCase));
            parts.Add(SourceWriter.Literal(path[position..start]));
            parts.Add($"global::System.Uri.EscapeDataString({Generated}.ApiFormat.Value(request.{member.Name}))");
            position = end + 1;
        }

        parts.Add(SourceWriter.Literal(path[position..]));
        var expression = string.Join(" + ", parts.Where(p => p != "\"\""));
        return expression.Length == 0 ? "\"\"" : expression;
    }

    private static void WriteRegistration(SourceWriter w, HostModel host, ProfileModel profile, OperationModel[] handled)
    {
        w.Line($"/// <summary>Registers <see cref=\"{host.Name}\" />{( handled.Length > 0 ? " and its mediator handlers" : "" )}.</summary>");
        w.Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"Rocket.Surgery.LaunchPad.Api.Client.Http\", \"{typeof(HttpClientGenerator).Assembly.GetName().Version}\")]");
        w.Open($"{host.Accessibility} static class {host.Name}ServiceCollectionExtensions");
        w.Line($"/// <summary>Registers <see cref=\"{host.Name}\" />, its named HttpClient and one mediator handler per operation.</summary>");
        w.Line("/// <returns>The HttpClient builder, to set the base address, handlers and resilience.</returns>");
        w.Open($"public static global::Microsoft.Extensions.DependencyInjection.IHttpClientBuilder Add{host.Name}(this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
        w.Line("global::System.ArgumentNullException.ThrowIfNull(services);");
        ClientEmit.WriteRegistrations(w, host, profile, handled);
        w.Line($"return global::Microsoft.Extensions.DependencyInjection.HttpClientFactoryServiceCollectionExtensions.AddHttpClient(services, {host.Name}.HttpClientName);");
        w.Close();
        w.Close();
    }



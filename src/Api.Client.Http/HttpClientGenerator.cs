using Microsoft.CodeAnalysis;

namespace Rocket.Surgery.LaunchPad.Api.Generators;

/// <summary>
///     Generates an HTTP client for every client operation host: one method per listed operation, named after the operation, plus one mediator
///     handler per operation (the shape depends on the mediator profile) and an <c>Add{Host}()</c> registration that returns the
///     <c>IHttpClientBuilder</c>.
/// </summary>
[Generator]
public sealed class HttpClientGenerator : IIncrementalGenerator
{
    private const string Tasks = "global::System.Threading.Tasks";
    private const string Ct = "cancellationToken";
    // Each transport package emits its helpers into its own namespace, so a project can reference several of them.
    private const string Generated = "global::Rocket.Surgery.LaunchPad.Api.Generated.Http";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(
            static output =>
            {
                HostPipeline.EmitMarker(output, HostKind.HttpClient);
                output.AddSource("Rocket.Surgery.LaunchPad.Api.Generated.ClientHelpers.g.cs", ClientHelpers);
            }
        );

        var hosts = HostPipeline.Hosts(context, HostKind.HttpClient);
        var assemblyName = context.CompilationProvider.Select(static (c, _) => c.AssemblyName ?? "Assembly");
        var mediatorGenerators = context.AnalyzerConfigOptionsProvider.Select(static (options, _) => HostPipeline.MediatorGenerators(options.GlobalOptions));
        context.RegisterSourceOutput(
            hosts.Combine(assemblyName).Combine(mediatorGenerators),
            static (output, pair) => Emit(output, pair.Left.Left, pair.Left.Right, pair.Right)
        );
    }

    private static void Emit(SourceProductionContext output, EquatableArray<HostModel> hosts, string assemblyName, EquatableArray<string>? mediatorGenerators)
    {
        var foundatio = new List<(HostModel Host, OperationModel Operation)>();
        foreach (var host in hosts)
        {
            foreach (var diagnostic in host.Diagnostics) output.ReportDiagnostic(diagnostic.ToDiagnostic());
            if (host.Profile is not { } profile) continue;
            if (HostPipeline.PlacementProblem(profile, mediatorGenerators) is { } problem)
            {
                output.ReportDiagnostic(DiagnosticInfo.Create(ApiDiagnostics.ClientHostInWrongProject, host.Location, host.Name, profile.Name, problem).ToDiagnostic());
            }

            foreach (var operation in HandledOperations(host, profile).Where(o => o.VisibleHandler is { }))
            {
                output.ReportDiagnostic(DiagnosticInfo.Create(ApiDiagnostics.HandWrittenHandlerVisible, operation.Location, operation.RequestDisplayName, operation.VisibleHandler!, host.Name).ToDiagnostic());
            }

            output.AddSource(host.FullyQualifiedName.Replace("global::", "") + ".HttpClient.g.cs", Write(host, profile, assemblyName, output));
            if (profile.ClientEmitter == ClientEmitter.Foundatio) foundatio.AddRange(HandledOperations(host, profile).Select(o => (host, o)));
            if (profile.ClientEmitter == ClientEmitter.ZeroAlloc) output.AddSource(host.FullyQualifiedName.Replace("global::", "") + ".ZeroAlloc.g.cs", WriteZeroAlloc(host));
        }

        // One request type, one handler: two client hosts handling the same operation is ambiguous for every mediator.
        foreach (var duplicate in hosts.Where(h => h.Profile is { })
                                       .SelectMany(h => HandledOperations(h, h.Profile!).Select(o => (Host: h, Operation: o)))
                                       .GroupBy(x => x.Operation.RequestType)
                                       .Where(g => g.Count() > 1))
        {
            var items = duplicate.ToArray();
            output.ReportDiagnostic(DiagnosticInfo.Create(ApiDiagnostics.DuplicateClientHandler, items[1].Operation.Location, items[0].Operation.RequestDisplayName, items[0].Host.Name, items[1].Host.Name).ToDiagnostic());
        }

        if (foundatio.Count > 0) output.AddSource("Rocket.Surgery.LaunchPad.Api.Generated.FoundatioModule.g.cs", WriteFoundatioModule(foundatio, assemblyName));
    }

    private static IEnumerable<OperationModel> HandledOperations(HostModel host, ProfileModel profile) =>
        profile.ClientEmitter == ClientEmitter.None ? [] : host.Operations.Where(o => o.Handlers && o.InputType is null);

    private static string Write(HostModel host, ProfileModel profile, string assemblyName, SourceProductionContext output)
    {
        var w = new SourceWriter();
        w.Line("// <auto-generated/>").Line("#nullable enable").Line("#pragma warning disable CS1591").Line();
        if (host.Namespace is { } ns) w.Open($"namespace {ns}");

        var version = typeof(HttpClientGenerator).Assembly.GetName().Version;
        w.Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"Rocket.Surgery.LaunchPad.Api.Client.Http\", \"{version}\")]");
        w.Open($"{host.Accessibility} partial class {host.Name}");
        w.Line($"/// <summary>The name of the <see cref=\"global::System.Net.Http.HttpClient\" /> this client sends through.</summary>");
        w.Line($"public const string HttpClientName = {SourceWriter.Literal(host.ClientName)};");
        w.Line();
        w.Line("private static readonly global::System.Text.Json.JsonSerializerOptions __jsonOptions = CreateJsonOptions();");
        w.Line("private readonly global::System.Net.Http.IHttpClientFactory __httpClientFactory;");
        w.Line();
        w.Line($"/// <summary>Creates the client. Register it with <c>services.Add{host.Name}()</c>.</summary>");
        w.Open($"public {host.Name}(global::System.Net.Http.IHttpClientFactory httpClientFactory)");
        w.Line("global::System.ArgumentNullException.ThrowIfNull(httpClientFactory);");
        w.Line("__httpClientFactory = httpClientFactory;");
        w.Close();
        w.Line();
        w.Open("private static global::System.Text.Json.JsonSerializerOptions CreateJsonOptions()");
        w.Line($"var options = new global::System.Text.Json.JsonSerializerOptions(global::System.Text.Json.JsonSerializerDefaults.{( host.JsonWebDefaults ? "Web" : "General" )});");
        w.Line("ConfigureJsonOptions(options);");
        w.Line("// Reflection-based metadata unless a JsonSerializerContext was supplied; native AOT apps add one in ConfigureJsonOptions.");
        w.Line("if (global::System.Text.Json.JsonSerializer.IsReflectionEnabledByDefault) options.TypeInfoResolver ??= ReflectionTypeInfoResolver();");
        w.Line("options.MakeReadOnly();");
        w.Line("return options;");
        w.Close();
        w.Line();
        // Only reached when reflection-based serialization is enabled; trimmed and native AOT apps disable it and supply a JsonSerializerContext.
        w.Line("[global::System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage(\"Trimming\", \"IL2026\", Justification = \"Only called when JsonSerializer.IsReflectionEnabledByDefault is true.\")]");
        w.Line("[global::System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage(\"AOT\", \"IL3050\", Justification = \"Only called when JsonSerializer.IsReflectionEnabledByDefault is true.\")]");
        w.Line("private static global::System.Text.Json.Serialization.Metadata.IJsonTypeInfoResolver? ReflectionTypeInfoResolver() => global::System.Text.Json.JsonSerializerOptions.Default.TypeInfoResolver;");
        w.Line();
        w.Line("/// <summary>Adjusts the JSON options, e.g. to insert a <c>JsonSerializerContext</c> for trimming and native AOT.</summary>");
        w.Line("static partial void ConfigureJsonOptions(global::System.Text.Json.JsonSerializerOptions options);");

        foreach (var operation in host.Operations)
        {
            w.Line();
            WriteMethod(w, host, operation);
        }

        var handled = HandledOperations(host, profile).ToArray();
        if (profile.ClientEmitter is ClientEmitter.HandlerInterface or ClientEmitter.HandlerInterfaceDiscovered)
        {
            foreach (var operation in handled)
            {
                if (operation.HandlerInterface is null || operation.HandlerMethodReturnType is null)
                {
                    output.ReportDiagnostic(DiagnosticInfo.Create(ApiDiagnostics.NoHandlerInterface, operation.Location, profile.Name, operation.RequestDisplayName, $"{host.Name}.{operation.Name}").ToDiagnostic());
                    continue;
                }

                w.Line();
                WriteHandler(w, host, profile, operation);
            }
        }
        else if (profile.ClientEmitter == ClientEmitter.None)
        {
            foreach (var operation in host.Operations)
            {
                output.ReportDiagnostic(DiagnosticInfo.Create(ApiDiagnostics.NoHandlerInterface, operation.Location, profile.Name, operation.RequestDisplayName, $"{host.Name}.{operation.Name}").ToDiagnostic());
            }
        }

        w.Close();
        w.Line();
        WriteRegistration(w, host, profile, handled, assemblyName);
        if (host.Namespace is { }) w.Close();
        return w.ToString();
    }

    private static void WriteMethod(SourceWriter w, HostModel host, OperationModel operation)
    {
        var parameter = operation.InputType ?? operation.RequestType;
        var jsonType = operation.ResponseIsNullableValueType ? operation.ResponseType : operation.ResponseTypeNotNull;
        w.Line($"/// <summary>Sends <see cref=\"{Cref(operation.RequestType)}\" /> to <c>{operation.Verb.ToString().ToUpperInvariant()} /{RouteText.Join(host.BaseRoute, operation.Route)}</c>.</summary>");
        var signature = operation.Kind switch
        {
            RequestKind.Stream => $"public async global::System.Collections.Generic.IAsyncEnumerable<{operation.ResponseType}> {operation.Name}({parameter} request, [global::System.Runtime.CompilerServices.EnumeratorCancellation] global::System.Threading.CancellationToken {Ct} = default)",
            RequestKind.Void => $"public async {Tasks}.Task {operation.Name}({parameter} request, global::System.Threading.CancellationToken {Ct} = default)",
            RequestKind.Unary or RequestKind.Infer => $"public async {Tasks}.Task<{operation.ResponseType}> {operation.Name}({parameter} request, global::System.Threading.CancellationToken {Ct} = default)",
            _ => throw new ArgumentOutOfRangeException(nameof(operation)),
        };
        w.Open(signature);
        w.Line("global::System.ArgumentNullException.ThrowIfNull(request);");
        w.Line($"var __url = {Url(host, operation)};");
        var query = operation.HasBody ? [] : operation.Members.Where(m => m.Source == BindingSource.Query).ToArray();
        var version = operation.Version ?? host.Version;
        if (query.Length > 0 || version is { })
        {
            w.Line($"var __query = new {Generated}.ApiQuery();");
            foreach (var member in query) w.Line($"__query.Add({SourceWriter.Literal(member.WireName)}, request.{member.Name});");
            if (version is { }) w.Line($"__query.Add(\"api-version\", {SourceWriter.Literal(version)});");
            w.Line("__url += __query.ToString();");
        }

        w.Line($"using var __message = new global::System.Net.Http.HttpRequestMessage(new global::System.Net.Http.HttpMethod({SourceWriter.Literal(operation.Verb.ToString().ToUpperInvariant())}), __url);");
        foreach (var header in operation.Members.Where(m => m.Source == BindingSource.Header))
        {
            w.Line($"if (request.{header.Name} is {{ }} __{header.Name}) __message.Headers.TryAddWithoutValidation({SourceWriter.Literal(header.WireName)}, {Generated}.ApiFormat.Value(__{header.Name}));");
        }

        if (operation.HasBody)
        {
            w.Line($"__message.Content = global::System.Net.Http.Json.JsonContent.Create(request, (global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<{parameter}>)__jsonOptions.GetTypeInfo(typeof({parameter})));");
        }

        w.Line($"Configure{operation.Name}(__message);");
        var completion = operation.Kind == RequestKind.Stream ? "global::System.Net.Http.HttpCompletionOption.ResponseHeadersRead" : "global::System.Net.Http.HttpCompletionOption.ResponseContentRead";
        w.Line($"using var __response = await __httpClientFactory.CreateClient(HttpClientName).SendAsync(__message, {completion}, {Ct}).ConfigureAwait(false);");
        if (operation.ResponseNullable && operation.Kind == RequestKind.Unary)
        {
            w.Line("if (__response.StatusCode == global::System.Net.HttpStatusCode.NotFound) return default;");
        }

        w.Line($"await {Generated}.ApiClientResponse.EnsureSuccessAsync(__response, {Ct}).ConfigureAwait(false);");
        switch (operation.Kind)
        {
            case RequestKind.Void:
                break;
            case RequestKind.Stream:
                w.Line($"var __typeInfo = (global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<{jsonType}>)__jsonOptions.GetTypeInfo(typeof({jsonType}));");
                w.Line($"await foreach (var __item in global::System.Threading.Tasks.TaskAsyncEnumerableExtensions.ConfigureAwait({Generated}.ApiClientResponse.ReadNdjsonAsync(__response, __typeInfo, {Ct}), false)) yield return __item;");
                break;
            case RequestKind.Unary:
            case RequestKind.Infer:
            default:
                w.Line($"var __typeInfo = (global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<{jsonType}>)__jsonOptions.GetTypeInfo(typeof({jsonType}));");
                w.Line($"return (await global::System.Net.Http.Json.HttpContentJsonExtensions.ReadFromJsonAsync(__response.Content, __typeInfo, {Ct}).ConfigureAwait(false))!;");
                break;
        }

        w.Close();
        w.Line();
        w.Line($"/// <summary>Adjusts the request for <c>{operation.Name}</c> before it is sent. Implement it in your part of <see cref=\"{host.Name}\" />.</summary>");
        w.Line($"partial void Configure{operation.Name}(global::System.Net.Http.HttpRequestMessage request);");
    }

    // The URL relative to the client's BaseAddress, with every route value escaped.
    private static string Url(HostModel host, OperationModel operation)
    {
        var path = RouteText.Join(host.BaseRoute, operation.Route);
        var parts = new List<string>();
        var position = 0;
        while (path.IndexOf('{', position) is var start and >= 0)
        {
            var end = path.IndexOf('}', start);
            var token = RouteText.Tokens(path.Substring(start, end - start + 1)).First();
            var member = operation.Members.First(m => m.Source == BindingSource.Route && string.Equals(m.WireName, token, StringComparison.OrdinalIgnoreCase));
            parts.Add(SourceWriter.Literal(path[position..start]));
            parts.Add($"global::System.Uri.EscapeDataString({Generated}.ApiFormat.Value(request.{member.Name}))");
            position = end + 1;
        }

        parts.Add(SourceWriter.Literal(path[position..]));
        var expression = string.Join(" + ", parts.Where(p => p != "\"\""));
        return expression.Length == 0 ? "\"\"" : expression;
    }

    private static void WriteHandler(SourceWriter w, HostModel host, ProfileModel profile, OperationModel operation)
    {
        var returnType = operation.HandlerMethodReturnType!;
        var handleMethod = operation.HandlerMethodName ?? "Handle";
        w.Line($"/// <summary>Handles <see cref=\"{Cref(operation.RequestType)}\" /> by sending it through <see cref=\"{host.Name}.{operation.Name}\" />.</summary>");
        w.Open($"public sealed class {operation.Name}Handler : {operation.HandlerInterface}");
        w.Line($"private readonly {host.Name} __client;");
        w.Line();
        w.Line($"public {operation.Name}Handler({host.Name} client) => __client = client;");
        w.Line();
        var call = $"__client.{operation.Name}(request, {Ct})";
        var isValueTask = returnType.StartsWith(Tasks + ".ValueTask", StringComparison.Ordinal);
        var returnsValue = returnType.Contains("<");
        string body;
        if (operation.Kind == RequestKind.Stream)
        {
            // Immediate.Handlers' stream handlers return ValueTask<IAsyncEnumerable<T>>.
            body = isValueTask ? $" => new {returnType}({call});" : $" => {call};";
        }
        else if (operation.Kind == RequestKind.Void && returnsValue)
        {
            // A Unit-returning void handler: the client method returns a Task, the handler returns Unit.
            body = null!;
            w.Open($"public async {returnType} {handleMethod}({operation.RequestType} request, global::System.Threading.CancellationToken {Ct})");
            w.Line($"await {call}.ConfigureAwait(false);");
            w.Line("return default;");
            w.Close();
        }
        else
        {
            body = isValueTask ? $" => new {returnType}({call});" : $" => {call};";
        }

        if (body is { }) w.Line($"public {returnType} {handleMethod}({operation.RequestType} request, global::System.Threading.CancellationToken {Ct}){body}");
        w.Close();
    }

    private static void WriteRegistration(SourceWriter w, HostModel host, ProfileModel profile, OperationModel[] handled, string assemblyName)
    {
        w.Line($"/// <summary>Registers <see cref=\"{host.Name}\" />{( handled.Length > 0 ? " and its mediator handlers" : "" )}.</summary>");
        w.Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"Rocket.Surgery.LaunchPad.Api.Client.Http\", \"{typeof(HttpClientGenerator).Assembly.GetName().Version}\")]");
        w.Open($"{host.Accessibility} static class {host.Name}ServiceCollectionExtensions");
        w.Line($"/// <summary>Registers <see cref=\"{host.Name}\" />, its named HttpClient and one mediator handler per operation.</summary>");
        w.Line("/// <returns>The HttpClient builder, to set the base address, handlers and resilience.</returns>");
        w.Open($"public static global::Microsoft.Extensions.DependencyInjection.IHttpClientBuilder Add{host.Name}(this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
        w.Line("global::System.ArgumentNullException.ThrowIfNull(services);");
        w.Line($"global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAddTransient<{host.Name}>(services);");
        if (profile.ClientEmitter == ClientEmitter.HandlerInterface)
        {
            foreach (var operation in handled.Where(o => o.HandlerInterface is { }))
            {
                w.Line(
                    $"global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAdd(services, global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor.Describe(typeof({operation.HandlerInterface}), typeof({host.Name}.{operation.Name}Handler), global::Microsoft.Extensions.DependencyInjection.ServiceLifetime.{profile.HandlerLifetime}));"
                );
            }
        }

        if (profile.ClientEmitter == ClientEmitter.Foundatio && handled.Length > 0) WriteFoundatioCheck(w, host, handled[0]);
        w.Line($"return global::Microsoft.Extensions.DependencyInjection.HttpClientFactoryServiceCollectionExtensions.AddHttpClient(services, {host.Name}.HttpClientName);");
        w.Close();
        w.Close();
    }

    // AddMediator() builds and freezes Foundatio's handler registry from the [FoundatioModule] assemblies it scans. If this host's assembly wasn't
    // among them (AddMediator ran before the assembly was loaded, or was given an assembly list without it), the handlers are missing for good:
    // fail here with what to do instead of at the first Send.
    private static void WriteFoundatioCheck(SourceWriter w, HostModel host, OperationModel first)
    {
        var message = $"Foundatio's handler registry was built without {host.Name}'s handlers. Call services.Add{host.Name}() before services.AddMediator(), "
                    + $"and if AddMediator is given assemblies, include the one that declares {host.Name}.";
        w.Open("foreach (var __descriptor in services)");
        // ImplementationInstance throws on a keyed descriptor.
        w.Line("if (__descriptor.IsKeyedService || __descriptor.ServiceType != typeof(global::Foundatio.Mediator.HandlerRegistry) || __descriptor.ImplementationInstance is not global::Foundatio.Mediator.HandlerRegistry __registry) continue;");
        w.Line($"if (!global::System.Linq.Enumerable.Any(__registry.Registrations, r => r.HandlerClassName == {SourceWriter.Literal(FoundatioHandlerName(host, first))})) throw new global::System.InvalidOperationException({SourceWriter.Literal(message)});");
        w.Line("break;");
        w.Close();
    }

    private static string FoundatioHandlerName(HostModel host, OperationModel operation) => $"{host.Name}_{operation.Name}_Handler";

    private static string FoundatioModuleClass(string assemblyName) =>
        "global::Rocket.Surgery.LaunchPad.Api.Generated." + new string([.. assemblyName.Select(c => char.IsLetterOrDigit(c) ? c : '_')]) + "_MediatorHandlers";

    // ZeroAlloc generates `internal partial interface IMediator` and `internal partial class MediatorService` per project with one Send overload
    // per handler it sees in syntax; it can't see ours, so the missing overloads are added to its partials and route to the client.
    private static string WriteZeroAlloc(HostModel host)
    {
        var w = new SourceWriter();
        w.Line("// <auto-generated/>").Line("#nullable enable").Line("#pragma warning disable CS1591").Line();
        w.Open("namespace ZeroAlloc.Mediator");
        var operations = host.Operations.Where(o => o.Handlers && o.InputType is null).ToArray();
        w.Open("internal partial interface IMediator");
        foreach (var operation in operations) w.Line(ZeroAllocSignature(operation, true) + ";");
        w.Close();
        w.Open("internal partial class MediatorService");
        foreach (var operation in operations)
        {
            var client = $"global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<{host.FullyQualifiedName}>(_services)";
            var call = $"{client}.{operation.Name}(request, ct)";
            switch (operation.Kind)
            {
                case RequestKind.Stream:
                    w.Line($"public {ZeroAllocSignature(operation, false)} => {call};");
                    break;
                case RequestKind.Void:
                    w.Open($"public async {ZeroAllocSignature(operation, false)}");
                    w.Line($"await {call}.ConfigureAwait(false);");
                    w.Line("return default;");
                    w.Close();
                    break;
                case RequestKind.Unary:
                case RequestKind.Infer:
                default:
                    w.Line($"public {ZeroAllocSignature(operation, false)} => new({call});");
                    break;
            }
        }

        w.Close();
        w.Close();
        return w.ToString();
    }

    private static string ZeroAllocSignature(OperationModel operation, bool withDefault)
    {
        var ct = "global::System.Threading.CancellationToken ct" + ( withDefault ? " = default" : "" );
        return operation.Kind == RequestKind.Stream
            ? $"global::System.Collections.Generic.IAsyncEnumerable<{operation.ResponseType}> CreateStream({operation.RequestType} request, {ct})"
            : $"{Tasks}.ValueTask<{( operation.Kind == RequestKind.Void ? "global::ZeroAlloc.Mediator.Unit" : operation.ResponseType )}> Send({operation.RequestType} request, {ct})";
    }

    // Foundatio's AddMediator() scans loaded assemblies for [FoundatioModule] and calls the first static *_MediatorHandlers.AddHandlers it finds.
    // The client library doesn't run Foundatio's generator, so this is the only module class in it.
    private static string WriteFoundatioModule(List<(HostModel Host, OperationModel Operation)> operations, string assemblyName)
    {
        var w = new SourceWriter();
        w.Line("// <auto-generated/>").Line("#nullable enable").Line("#pragma warning disable").Line();
        w.Line("[assembly: global::Foundatio.Mediator.FoundatioModule]");
        w.Line();
        w.Open("namespace Rocket.Surgery.LaunchPad.Api.Generated");
        w.Open($"public static class {FoundatioModuleClass(assemblyName).Split('.').Last()}");
        w.Open("public static void AddHandlers(global::Microsoft.Extensions.DependencyInjection.IServiceCollection services, global::Foundatio.Mediator.HandlerRegistry registry)");
        foreach (var (host, operation) in operations)
        {
            var handlerName = FoundatioHandlerName(host, operation);
            w.Line("registry.AddHandler(new global::Foundatio.Mediator.HandlerRegistration(");
            w.Line($"    global::Foundatio.Mediator.MessageTypeKey.Get(typeof({operation.RequestType})),");
            w.Line($"    {SourceWriter.Literal(handlerName)},");
            w.Line("    static async (mediator, message, callContext, cancellationToken, responseType, skipAuthorization) =>");
            w.Line("    {");
            w.Line($"        var client = ({host.FullyQualifiedName})((global::System.IServiceProvider)mediator).GetService(typeof({host.FullyQualifiedName}))!;");
            w.Line(
                operation.Kind == RequestKind.Void
                    ? $"        await client.{operation.Name}(({operation.RequestType})message, cancellationToken).ConfigureAwait(false); return null;"
                    : operation.Kind == RequestKind.Stream
                        ? $"        return client.{operation.Name}(({operation.RequestType})message, cancellationToken);"
                        : $"        return await client.{operation.Name}(({operation.RequestType})message, cancellationToken).ConfigureAwait(false);"
            );
            w.Line("    },");
            w.Line("    null,");
            w.Line("    true,");
            w.Line($"    sourceHandlerName: {SourceWriter.Literal(host.Name)},");
            w.Line($"    methodName: {SourceWriter.Literal(operation.Name)}));");
        }

        w.Close();
        w.Close();
        w.Close();
        return w.ToString();
    }

    private static string Cref(string type) => type.Replace("global::", "").Replace('<', '{').Replace('>', '}');

    private const string ClientHelpers = """
// <auto-generated/>
#nullable enable
#pragma warning disable
namespace Rocket.Surgery.LaunchPad.Api.Generated.Http
{
    /// <summary>Formats a value for a URL: invariant culture, enums by name, booleans in lowercase.</summary>
    [global::Microsoft.CodeAnalysis.EmbeddedAttribute]
    internal static class ApiFormat
    {
        public static string Value(object? value) => value switch
        {
            null => "",
            bool b => b ? "true" : "false",
            global::System.Enum e => e.ToString(),
            global::System.IFormattable f => f.ToString(null, global::System.Globalization.CultureInfo.InvariantCulture),
            _ => value.ToString() ?? "",
        };
    }

    /// <summary>Builds a query string, skipping nulls and repeating keys for collections.</summary>
    [global::Microsoft.CodeAnalysis.EmbeddedAttribute]
    internal sealed class ApiQuery
    {
        private readonly global::System.Text.StringBuilder _builder = new();

        public void Add(string name, object? value)
        {
            if (value is null) return;
            if (value is not string && value is global::System.Collections.IEnumerable items)
            {
                foreach (var item in items) Add(name, item);
                return;
            }

            _builder.Append(_builder.Length == 0 ? '?' : '&')
                    .Append(global::System.Uri.EscapeDataString(name))
                    .Append('=')
                    .Append(global::System.Uri.EscapeDataString(ApiFormat.Value(value)));
        }

        public override string ToString() => _builder.ToString();
    }

    [global::Microsoft.CodeAnalysis.EmbeddedAttribute]
    internal static class ApiClientResponse
    {
        /// <summary>Throws an <see cref="global::System.Net.Http.HttpRequestException" /> with the status code and the response body (usually ProblemDetails).</summary>
        public static async global::System.Threading.Tasks.Task EnsureSuccessAsync(global::System.Net.Http.HttpResponseMessage response, global::System.Threading.CancellationToken cancellationToken)
        {
            if (response.IsSuccessStatusCode) return;
            var body = response.Content is { } content ? await content.ReadAsStringAsync(cancellationToken).ConfigureAwait(false) : "";
            var message = $"{(int)response.StatusCode} {response.ReasonPhrase} from {response.RequestMessage?.Method} {response.RequestMessage?.RequestUri}" + (body.Length > 0 ? ": " + body : "");
            throw new global::System.Net.Http.HttpRequestException(message, null, response.StatusCode);
        }

        /// <summary>Reads newline-delimited JSON as it arrives.</summary>
        public static async global::System.Collections.Generic.IAsyncEnumerable<T> ReadNdjsonAsync<T>(
            global::System.Net.Http.HttpResponseMessage response,
            global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<T> typeInfo,
            [global::System.Runtime.CompilerServices.EnumeratorCancellation] global::System.Threading.CancellationToken cancellationToken)
        {

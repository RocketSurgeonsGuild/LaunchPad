using System.Collections.Immutable;
using System.Reflection.Metadata;
using System.Reflection.PortableExecutable;
using System.Text;

namespace Rocket.Surgery.LaunchPad.Primitives.Tasks;

/// <summary>A type a referenced assembly lists in its JSON context manifest, as C# names it.</summary>
public sealed record JsonContextEntry(string TypeName, string PropertyName);

/// <summary>
///     Reads the <c>[assembly: JsonContextType(typeof(X))]</c> manifests of referenced assemblies, and writes the application's JSON context from
///     them. Kept apart from the MSBuild task so it can be tested without MSBuild.
/// </summary>
public static class JsonContextManifest
{
    private const string AttributeNamespace = "Rocket.Surgery.LaunchPad.Primitives";
    private const string AttributeName = "JsonContextTypeAttribute";
    private const string PrimitivesAssembly = "Rocket.Surgery.LaunchPad.Primitives";

    // Members of JsonSerializerContext a generated property must not hide.
    private static readonly HashSet<string> Reserved = [with(StringComparer.Ordinal), "Default", "Options", "GeneratedSerializerOptions", "GetTypeInfo"];

    /// <summary>Every type the assemblies list, once, each with a property name unique on the context.</summary>
    public static ImmutableArray<JsonContextEntry> Read(IEnumerable<string> assemblyPaths)
    {
        var listed = new SortedDictionary<string, string>(StringComparer.Ordinal);
        foreach (var path in assemblyPaths)
        {
            foreach (var (serialized, propertyName) in ReadAssembly(path))
            {
                if (SerializedTypeName.Parse(serialized) is not { } parsed) continue;
                if (!listed.ContainsKey(parsed.TypeName) || propertyName is { }) listed[parsed.TypeName] = propertyName ?? parsed.PropertyName;
            }
        }

        var used = new HashSet<string>(Reserved, StringComparer.Ordinal);
        var entries = ImmutableArray.CreateBuilder<JsonContextEntry>();
        foreach (var pair in listed)
        {
            var name = pair.Value;
            var unique = name;
            for (var i = 2; !used.Add(unique); i++) unique = name + i;
            entries.Add(new(pair.Key, unique));
        }

        return entries.ToImmutable();
    }

    /// <summary>The source of the JSON context, and of the Joint that chains it into the application's JSON options.</summary>
    public static string Write(ImmutableArray<JsonContextEntry> entries, string? rootNamespace, string contextName)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("// Generated by Rocket.Surgery.LaunchPad.Primitives from the JSON context manifests of the referenced assemblies.");
        builder.AppendLine("// Turn it off with <LaunchPadGenerateJsonContext>false</LaunchPadGenerateJsonContext>.");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("#pragma warning disable");
        var indent = "";
        if (!string.IsNullOrWhiteSpace(rootNamespace))
        {
            builder.Append("namespace ").AppendLine(rootNamespace);
            builder.AppendLine("{");
            indent = "    ";
        }

        builder.Append(indent).AppendLine("/// <summary>The JSON context of the types the referenced assemblies list, so they serialize without reflection.</summary>");
        foreach (var entry in entries)
        {
            builder.Append(indent)
                   .Append("[global::System.Text.Json.Serialization.JsonSerializable(typeof(")
                   .Append(entry.TypeName)
                   .Append("), TypeInfoPropertyName = \"")
                   .Append(entry.PropertyName)
                   .AppendLine("\")]");
        }

        // No [GeneratedCode] here: the System.Text.Json source generator puts one on its part of the class.
        builder.Append(indent).Append("internal sealed partial class ").Append(contextName).AppendLine(" : global::System.Text.Json.Serialization.JsonSerializerContext;");
        builder.AppendLine();
        builder.Append(indent).Append("/// <summary>Chains <see cref=\"").Append(contextName).AppendLine("\" /> into the application's JSON options.</summary>");
        builder.Append(indent).AppendLine("[global::Joinery.Dovetail.Attributes.DovetailExport]");
        builder.Append(indent).AppendLine("[global::System.CodeDom.Compiler.GeneratedCode(\"Rocket.Surgery.LaunchPad.Primitives\", \"generated\")]");
        builder.Append(indent).Append("internal sealed class ").Append(contextName).AppendLine("Joint : global::Joinery.Dovetail.Joints.IServiceJoint");
        builder.Append(indent).AppendLine("{");
        builder.Append(indent).AppendLine("    public void Register(global::Joinery.Dovetail.IDovetailContext context, global::Microsoft.Extensions.DependencyInjection.IServiceCollection services) =>");
        builder.Append(indent)
               .Append("        global::Rocket.Surgery.LaunchPad.Primitives.LaunchPadJsonServiceCollectionExtensions.AddJsonTypeInfoResolver(services, ")
               .Append(contextName)
               .AppendLine(".Default);");
        builder.Append(indent).AppendLine("}");
        if (indent.Length > 0) builder.AppendLine("}");
        return builder.ToString();
    }

    private static IEnumerable<(string Serialized, string? PropertyName)> ReadAssembly(string path)
    {
        if (!File.Exists(path)) yield break;
        using var stream = File.OpenRead(path);
        using var pe = new PEReader(stream);
        if (!pe.HasMetadata) yield break;
        var metadata = pe.GetMetadataReader();
        if (!metadata.IsAssembly) yield break;

        // Only an assembly that references Primitives (or is it) can carry the attribute: the framework's are skipped without a look.
        var assemblyName = metadata.GetString(metadata.GetAssemblyDefinition().Name);
        if (assemblyName != PrimitivesAssembly
         && !metadata.AssemblyReferences.Any(r => metadata.GetString(metadata.GetAssemblyReference(r).Name) == PrimitivesAssembly))
        {
            yield break;
        }

        var provider = new StringTypeProvider();
        foreach (var handle in metadata.GetAssemblyDefinition().GetCustomAttributes())
        {
            var attribute = metadata.GetCustomAttribute(handle);
            if (!IsManifestAttribute(metadata, attribute)) continue;
            var value = attribute.DecodeValue(provider);
            if (value.FixedArguments.Length != 1 || value.FixedArguments[0].Value is not string serialized) continue;
            var propertyName = value.NamedArguments.FirstOrDefault(a => a.Name == "TypeInfoPropertyName").Value as string;
            yield return (serialized, propertyName);
        }
    }

    private static bool IsManifestAttribute(MetadataReader metadata, CustomAttribute attribute)
    {
        switch (attribute.Constructor.Kind)
        {
            case HandleKind.MemberReference:
                var parent = metadata.GetMemberReference((MemberReferenceHandle)attribute.Constructor).Parent;
                if (parent.Kind != HandleKind.TypeReference) return false;
                var reference = metadata.GetTypeReference((TypeReferenceHandle)parent);
                return metadata.GetString(reference.Name) == AttributeName && metadata.GetString(reference.Namespace) == AttributeNamespace;
            case HandleKind.MethodDefinition:
                var definition = metadata.GetTypeDefinition(metadata.GetMethodDefinition((MethodDefinitionHandle)attribute.Constructor).GetDeclaringType());
                return metadata.GetString(definition.Name) == AttributeName && metadata.GetString(definition.Namespace) == AttributeNamespace;
            case HandleKind.ModuleDefinition:
                break;
            case HandleKind.TypeReference:
                break;
            case HandleKind.TypeDefinition:
                break;
            case HandleKind.FieldDefinition:
                break;
            case HandleKind.Parameter:
                break;
            case HandleKind.InterfaceImplementation:
                break;
            case HandleKind.Constant:
                break;
            case HandleKind.CustomAttribute:
                break;
            case HandleKind.DeclarativeSecurityAttribute:
                break;
            case HandleKind.StandaloneSignature:
                break;
            case HandleKind.EventDefinition:
                break;
            case HandleKind.PropertyDefinition:
                break;
            case HandleKind.MethodImplementation:
                break;
            case HandleKind.ModuleReference:
                break;
            case HandleKind.TypeSpecification:
                break;
            case HandleKind.AssemblyDefinition:
                break;
            case HandleKind.AssemblyFile:
                break;
            case HandleKind.AssemblyReference:
                break;
            case HandleKind.ExportedType:
                break;
            case HandleKind.GenericParameter:
                break;
            case HandleKind.MethodSpecification:
                break;
            case HandleKind.GenericParameterConstraint:
                break;
            case HandleKind.ManifestResource:
                break;
            case HandleKind.Document:
                break;
            case HandleKind.MethodDebugInformation:
                break;
            case HandleKind.LocalScope:
                break;
            case HandleKind.LocalVariable:
                break;
            case HandleKind.LocalConstant:
                break;
            case HandleKind.ImportScope:
                break;
            case HandleKind.CustomDebugInformation:
                break;
            case HandleKind.NamespaceDefinition:
                break;
            case HandleKind.UserString:
                break;
            case HandleKind.String:
                break;
            case HandleKind.Blob:
                break;
            case HandleKind.Guid:
                break;
            default:
                return false;
        }

        return false;
    }

    // Decodes the attribute's arguments as text: a typeof argument is stored as its serialized type name.
    private sealed class StringTypeProvider : ICustomAttributeTypeProvider<string>
    {
        public string GetPrimitiveType(PrimitiveTypeCode typeCode) => typeCode.ToString();
        public string GetSystemType() => "System.Type";
        public string GetSZArrayType(string elementType) => elementType + "[]";
        public string GetTypeFromDefinition(MetadataReader reader, TypeDefinitionHandle handle, byte rawTypeKind)
        {
            var definition = reader.GetTypeDefinition(handle);
            return reader.GetString(definition.Namespace) + "." + reader.GetString(definition.Name);
        }

        // The namespace matters: the decoder asks IsSystemType of a typeof parameter's type.
        public string GetTypeFromReference(MetadataReader reader, TypeReferenceHandle handle, byte rawTypeKind)
        {
            var reference = reader.GetTypeReference(handle);
            return reader.GetString(reference.Namespace) + "." + reader.GetString(reference.Name);
        }
        public string GetTypeFromSerializedName(string name) => name;
        public PrimitiveTypeCode GetUnderlyingEnumType(string type) => PrimitiveTypeCode.Int32;
        public bool IsSystemType(string type) => type == "System.Type";
    }
}

/// <summary>Turns a serialized type name (<c>Ns.Outer+Inner`1[[Ns.Arg, Asm]][], Asm</c>) into the name C# uses for it.</summary>
public static class SerializedTypeName
{
    /// <summary>The C# name of a serialized type name, and a property name for it on a JSON context; null when the name can't be read.</summary>
    public static (string TypeName, string PropertyName)? Parse(string serialized)
    {
        try
        {
            var index = 0;
            var type = Parse(serialized, ref index);
            return (type.ToCSharp(), type.PropertyName());
        }
        catch (FormatException)
        {
            return null;
        }
    }

    public static string? ToCSharp(string serialized) => Parse(serialized)?.TypeName;

    private sealed class ParsedType(string name, List<ParsedType> arguments, List<string> arraySuffixes)
    {
        public string ToCSharp()
        {
            // Generic arguments belong to the segments of a nested chain by each segment's arity: Outer`1+Inner`1[[A],[B]] is Outer<A>.Inner<B>.
            var segments = name.Split('+');
            var result = new StringBuilder("global::");
            var next = 0;
            for (var s = 0; s < segments.Length; s++)
            {
                if (s > 0) result.Append('.');
                var segment = segments[s];
                var tick = segment.IndexOf('`');
                if (tick < 0)
                {
                    result.Append(segment);
                    continue;
                }

                result.Append(segment, 0, tick);
                var arity = int.Parse(segment[( tick + 1 )..], System.Globalization.CultureInfo.InvariantCulture);
                if (next + arity > arguments.Count) throw new FormatException("Too few generic arguments.");
                result.Append('<').Append(string.Join(", ", arguments.Skip(next).Take(arity).Select(a => a.ToCSharp()))).Append('>');
                next += arity;
            }

            foreach (var suffix in arraySuffixes) result.Append(suffix);
            return result.ToString();
        }

        // The type's own name and the types it is nested in, without the namespace: CreateRocket+Request is CreateRocketRequest,
        // List`1[[RocketModel]] is ListOfRocketModel, RocketModel[] is RocketModelArray.
        public string PropertyName()
        {
            var segments = name.Split('+');
            var first = segments[0];
            segments[0] = first[( first.LastIndexOf('.') + 1 )..];
            var result = new StringBuilder();
            foreach (var segment in segments)
            {
                var tick = segment.IndexOf('`');
                result.Append(tick < 0 ? segment : segment[..tick]);
            }

            if (arguments.Count > 0) result.Append("Of").Append(string.Join("And", arguments.Select(a => a.PropertyName())));
            foreach (var _ in arraySuffixes) result.Append("Array");
            return result.ToString();
        }
    }

    private static ParsedType Parse(string text, ref int index)
    {
        var start = index;
        while (index < text.Length && text[index] is not ( '[' or ']' or ',' )) index++;
        var name = text[start..index].Trim();
        if (name.Length == 0) throw new FormatException("Missing type name.");

        var arguments = new List<ParsedType>();
        // `[[` (or `[X` but not `[]` / `[,`) opens generic arguments.
        if (index < text.Length && text[index] == '[' && index + 1 < text.Length && text[index + 1] is not ( ']' or ',' ))
        {
            index++;
            while (true)
            {
                if (index < text.Length && text[index] == '[')
                {
                    index++;
                    arguments.Add(Parse(text, ref index));
                    SkipAssemblyName(text, ref index);
                    Expect(text, ref index, ']');
                }
                else
                {
                    arguments.Add(Parse(text, ref index));
                }

                if (index < text.Length && text[index] == ',')
                {
                    index++;
                    continue;
                }

                Expect(text, ref index, ']');
                break;
            }
        }

        var arrays = new List<string>();
        while (index < text.Length && text[index] == '[' && index + 1 < text.Length && text[index + 1] is ']' or ',')
        {
            var close = text.IndexOf(']', index);
            if (close < 0) throw new FormatException("Unclosed array.");
            arrays.Add(text.Substring(index, close - index + 1));
            index = close + 1;
        }

        return new(name, arguments, arrays);
    }

    // After a type inside [ ], an optional ", Assembly, Version=…" runs to the closing bracket.
    private static void SkipAssemblyName(string text, ref int index)
    {
        if (index >= text.Length || text[index] != ',') return;
        var depth = 0;
        while (index < text.Length)
        {
            var c = text[index];
            if (c == '[')
            {
                depth++;
            }
            else if (c == ']')
            {
                if (depth == 0) return;
                depth--;
            }

            index++;
        }
    }

    private static void Expect(string text, ref int index, char expected)
    {
        if (index >= text.Length || text[index] != expected) throw new FormatException($"Expected '{expected}' at {index}.");
        index++;
    }
}

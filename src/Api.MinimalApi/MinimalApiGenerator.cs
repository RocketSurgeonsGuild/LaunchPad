using Microsoft.CodeAnalysis;

namespace Rocket.Surgery.LaunchPad.Api.Generators;

/// <summary>
///     Generates a <c>Map{Host}()</c> extension for every Minimal API operation host: a route group under <c>/{RoutePrefix}/{Group}</c> with one
///     endpoint per listed operation, dispatched through the mediator profile.
/// </summary>
/// <remarks>
///     <para>
///         The Request Delegate Generator cannot see generated source, so a lambda passed to <c>MapGet</c> here would fall back to the reflection-based
///         request delegate factory and break trimming and native AOT. Instead each operation gets what the Request Delegate Generator would have
///         written: a typed handler method, and a <c>RequestDelegate</c> that binds the route, query, headers, services and body itself (with
///         <c>TryParse</c> and <c>JsonTypeInfo</c>), calls the handler and executes its result.
///     </para>
///     <para>
///         The handler's <see cref="System.Reflection.MethodInfo" /> and its result type's <c>IEndpointMetadataProvider</c> metadata are added to the
///         endpoint, so ApiExplorer and OpenAPI describe it exactly as they would a hand-written typed lambda.
///     </para>
/// </remarks>
[Generator]
public sealed class MinimalApiGenerator : IIncrementalGenerator
{
    private const string Http = "global::Microsoft.AspNetCore.Http";
    private const string Results = Http + ".HttpResults";
    private const string Ct = "__cancellationToken";
    private const string Generated = "global::Rocket.Surgery.LaunchPad.Api.Generated";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(
            static output =>
            {
                HostPipeline.EmitMarker(output, HostKind.MinimalApi);
                output.AddSource("Rocket.Surgery.LaunchPad.Api.Generated.ServerHelpers.g.cs", ServerHelpers);
            }
        );

        var hosts = HostPipeline.Hosts(context, HostKind.MinimalApi);
        context.RegisterSourceOutput(hosts, static (output, models) => Emit(output, models));
    }

    private static void Emit(SourceProductionContext output, EquatableArray<HostModel> hosts)
    {
        // Endpoint names are global to an application: an operation listed on two hosts gets its host noun in front.
        var duplicateNames = hosts.SelectMany(h => h.Operations.Select(o => o.EndpointName)).GroupBy(n => n).Where(g => g.Count() > 1).Select(g => g.Key).ToHashSet();
        foreach (var host in hosts)
        {
            foreach (var diagnostic in host.Diagnostics) output.ReportDiagnostic(diagnostic.ToDiagnostic());
            if (host.Profile is null) continue;
            output.AddSource(host.FullyQualifiedName.Replace("global::", "") + ".MinimalApi.g.cs", Write(host, host.Profile, duplicateNames, output));
        }

        foreach (var duplicate in hosts.SelectMany(h => h.Operations.Select(o => (Host: h, Operation: o)))
                                       .GroupBy(x => (x.Operation.Verb, Route: "/" + RouteText.Join(x.Host.BaseRoute, x.Operation.Route).ToLowerInvariant()))
                                       .Where(g => g.Select(x => x.Host.Name).Distinct().Count() > 1))
        {
            var items = duplicate.ToArray();
            output.ReportDiagnostic(
                DiagnosticInfo.Create(ApiDiagnostics.DuplicateRoute, items[1].Operation.Location, Verb(duplicate.Key.Verb), duplicate.Key.Route, items[0].Host.Name, items[1].Host.Name)
                              .ToDiagnostic()
            );
        }
    }

    private static string Write(HostModel host, ProfileModel profile, HashSet<string> duplicateNames, SourceProductionContext output)
    {
        var w = new SourceWriter();
        w.Line("// <auto-generated/>").Line("#nullable enable").Line("#pragma warning disable CS1591").Line();
        if (host.Namespace is { } ns) w.Open($"namespace {ns}");

        w.Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"Rocket.Surgery.LaunchPad.Api.MinimalApi\", \"{typeof(MinimalApiGenerator).Assembly.GetName().Version}\")]");
        w.Open($"{host.Accessibility} static partial class {host.Name}");
        w.Line("/// <summary>")
         .Line($"///     Maps the operations of <see cref=\"{host.Name}\" /> under <c>/{host.BaseRoute}</c>.")
         .Line("/// </summary>")
         .Line("/// <returns>The route group, to add metadata or conventions to every operation.</returns>");
        w.Open($"public static global::Microsoft.AspNetCore.Routing.RouteGroupBuilder Map{host.Name}(this global::Microsoft.AspNetCore.Routing.IEndpointRouteBuilder endpoints)");
        w.Line("global::System.ArgumentNullException.ThrowIfNull(endpoints);");
        w.Line($"var group = global::Microsoft.AspNetCore.Builder.EndpointRouteBuilderExtensions.MapGroup(endpoints, {SourceWriter.Literal("/" + host.BaseRoute)});");
        w.Line($"global::Microsoft.AspNetCore.Http.OpenApiRouteHandlerBuilderExtensions.WithTags(group, {SourceWriter.Literal(Naming.HostNoun(host.Name))});");

        var mapped = new List<(OperationModel Operation, string Service)>();
        foreach (var operation in host.Operations)
        {
            if (ServerDispatch.ServiceType(profile, operation) is not { } service)
            {
                output.ReportDiagnostic(
                    DiagnosticInfo.Create(ApiDiagnostics.FeatureSkipped, operation.Location, operation.Name, host.Name, $"the {profile.Name} profile cannot dispatch {KindName(operation.Kind)} operations")
                                  .ToDiagnostic()
                );
                continue;
            }

            WriteMapping(w, host, profile, operation, service, duplicateNames.Contains(operation.EndpointName));
            mapped.Add((operation, service));
        }

        w.Line("return group;");
        w.Close();

        foreach (var (operation, service) in mapped)
        {
            w.Line();
            WriteHandler(w, host, profile, operation, service);
            w.Line();
            WriteRequestDelegate(w, profile, operation, service);
            w.Line();
            w.Line($"/// <summary>Customises the generated <c>{operation.Name}</c> endpoint. Implement it in your part of <see cref=\"{host.Name}\" />.</summary>");
            w.Line($"static partial void Configure{operation.Name}(global::Microsoft.AspNetCore.Builder.IEndpointConventionBuilder endpoint);");
        }

        w.Close();
        if (host.Namespace is { }) w.Close();
        return w.ToString();
    }

    private static void WriteMapping(SourceWriter w, HostModel host, ProfileModel profile, OperationModel operation, string service, bool prefixName)
    {
        var (returnType, _) = ReturnType(profile, operation);
        w.Open("");
        w.Line(
            $"var endpoint = global::Microsoft.AspNetCore.Builder.EndpointRouteBuilderExtensions.MapMethods(group, {SourceWriter.Literal(operation.Route.Length == 0 ? "" : "/" + operation.Route.Trim('/'))}, new[] {{ {SourceWriter.Literal(Verb(operation.Verb))} }}, new {Http}.RequestDelegate(__{operation.Name}RequestDelegate));"
        );
        // The typed handler is what ApiExplorer and OpenAPI read: its parameters, their binding attributes and its result type.
        w.Line($"var method = typeof({host.Name}).GetMethod(nameof(__{operation.Name}), global::System.Reflection.BindingFlags.NonPublic | global::System.Reflection.BindingFlags.Static)!;");
        w.Line("global::Microsoft.AspNetCore.Builder.RoutingEndpointConventionBuilderExtensions.WithMetadata(endpoint, method);");
        w.Line($"endpoint.Add(builder => {Generated}.ApiEndpointMetadata.Populate<{Unwrap(returnType)}>(method, builder));");
        // ApiExplorer reads each parameter's binding from IParameterBindingMetadata, which the Request Delegate Generator would have added.
        w.Line("var parameters = method.GetParameters();");
        var index = 0;
        foreach (var parameter in HandlerParameters(operation, service))
        {
            w.Line($"global::Microsoft.AspNetCore.Builder.RoutingEndpointConventionBuilderExtensions.WithMetadata(endpoint, new {Generated}.ApiParameterBindingMetadata(parameters[{index}], {( parameter.HasTryParse ? "true" : "false" )}, {( parameter.IsOptional ? "true" : "false" )}));");
            index++;
        }
        if (operation.HasBody)
        {
            w.Line($"global::Microsoft.AspNetCore.Builder.RoutingEndpointConventionBuilderExtensions.WithMetadata(endpoint, new {Generated}.ApiAcceptsMetadata(typeof({operation.WireType})));");
        }

        // The request delegate answers 400 when a body, route, query or header value can't be bound.
        if (operation.HasBody || operation.Members.Any(m => m.Source is BindingSource.Route or BindingSource.Query or BindingSource.Header))
        {
            w.Line(
                "global::Microsoft.AspNetCore.Builder.RoutingEndpointConventionBuilderExtensions.WithMetadata(endpoint, new global::Microsoft.AspNetCore.Http.ProducesResponseTypeMetadata(400, typeof(global::Microsoft.AspNetCore.Mvc.ProblemDetails), new[] { \"application/problem+json\" }));"
            );
        }

        var name = prefixName ? Naming.HostNoun(host.Name) + operation.EndpointName : operation.EndpointName;
        w.Line($"global::Microsoft.AspNetCore.Builder.RoutingEndpointConventionBuilderExtensions.WithName(endpoint, {SourceWriter.Literal(name)});");
        if (operation.Summary is { } summary) w.Line($"global::Microsoft.AspNetCore.Http.OpenApiRouteHandlerBuilderExtensions.WithSummary(endpoint, {SourceWriter.Literal(summary)});");
        if (operation.Description is { } description) w.Line($"global::Microsoft.AspNetCore.Http.OpenApiRouteHandlerBuilderExtensions.WithDescription(endpoint, {SourceWriter.Literal(description)});");
        if (!operation.Tags.IsEmpty) w.Line($"global::Microsoft.AspNetCore.Http.OpenApiRouteHandlerBuilderExtensions.WithTags(endpoint, {string.Join(", ", operation.Tags.Select(SourceWriter.Literal))});");
        foreach (var policy in operation.Policies) w.Line($"global::Microsoft.AspNetCore.Builder.AuthorizationEndpointConventionBuilderExtensions.RequireAuthorization(endpoint, {SourceWriter.Literal(policy)});");
        if (!operation.Roles.IsEmpty || !operation.AuthenticationSchemes.IsEmpty)
        {
            var settings = new List<string>();
            if (!operation.Roles.IsEmpty) settings.Add($"Roles = {SourceWriter.Literal(string.Join(",", operation.Roles))}");
            if (!operation.AuthenticationSchemes.IsEmpty) settings.Add($"AuthenticationSchemes = {SourceWriter.Literal(string.Join(",", operation.AuthenticationSchemes))}");
            w.Line($"global::Microsoft.AspNetCore.Builder.AuthorizationEndpointConventionBuilderExtensions.RequireAuthorization(endpoint, new global::Microsoft.AspNetCore.Authorization.AuthorizeAttribute {{ {string.Join(", ", settings)} }});");
        }

        if (operation.AllowAnonymous) w.Line("global::Microsoft.AspNetCore.Builder.AuthorizationEndpointConventionBuilderExtensions.AllowAnonymous(endpoint);");
        w.Line($"Configure{operation.Name}(endpoint);");
        w.Close();
    }

    // The typed handler: bound values in, the mediator call, a typed result out. Its signature is what OpenAPI describes.
    private static void WriteHandler(SourceWriter w, HostModel host, ProfileModel profile, OperationModel operation, string service)
    {
        var (returnType, isAsync) = ReturnType(profile, operation);
        w.Line($"/// <summary>Handles <c>{Verb(operation.Verb)} /{RouteText.Join(host.BaseRoute, operation.Route)}</c>.</summary>");
        w.Open($"private static {( isAsync ? "async " : "" )}{returnType} __{operation.Name}({string.Join(", ", HandlerParameters(operation, service).Select(p => $"{p.Attribute} {p.Type} {p.Name}"))})");
        WriteRequest(w, operation);
        WriteDispatchAndResult(w, host, profile, operation);
        w.Close();
    }

    // What the Request Delegate Generator would have written: bind every parameter from the HttpContext, call the handler, execute the result.
    private static void WriteRequestDelegate(SourceWriter w, ProfileModel profile, OperationModel operation, string service)
    {
        w.Open($"private static async global::System.Threading.Tasks.Task __{operation.Name}RequestDelegate({Http}.HttpContext httpContext)");
        w.Line($"var {Ct} = httpContext.RequestAborted;");
        foreach (var member in operation.Members)
        {
            switch (member.Source)
            {
                case BindingSource.Route:
                    WriteParse(w, member, $"httpContext.Request.RouteValues[{SourceWriter.Literal(member.WireName)}]?.ToString()", "route value");
                    break;
                case BindingSource.Query:
                    if (!operation.HasBody) WriteParse(w, member, $"httpContext.Request.Query[{SourceWriter.Literal(member.WireName)}]", "query string value");
                    break;
                case BindingSource.Header:
                    WriteParse(w, member, $"httpContext.Request.Headers[{SourceWriter.Literal(member.WireName)}]", "header");
                    break;
                case BindingSource.Service:
                    w.Line($"var {Parameter(member)} = global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<{member.TypeWithoutNullable}>(httpContext.RequestServices);");
                    break;
                case BindingSource.Body:
                case BindingSource.Ignored:
                    break;
                default:
                    break;
            }
        }

        if (operation.HasBody)
        {
            w.Line($"var (__read, __body) = await {Generated}.ApiBinding.ReadBodyAsync<{operation.WireType}>(httpContext, {Ct}).ConfigureAwait(false);");
            w.Line("if (!__read) return;");
        }

        w.Line($"var {ServerDispatch.SenderParameter} = global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<{service}>(httpContext.RequestServices);");
        var arguments = HandlerParameters(operation, service).Select(p => p.Name);
        var (_, isAsync) = ReturnType(profile, operation);
        w.Line($"var __result = {( isAsync ? "await " : "" )}__{operation.Name}({string.Join(", ", arguments)}){( isAsync ? ".ConfigureAwait(false)" : "" )};");
        w.Line("await __result.ExecuteAsync(httpContext).ConfigureAwait(false);");
        w.Close();
    }

    // Parses one route, query or header value into a local named after the member. A missing required value or an unparsable one is a 400.
    private static void WriteParse(SourceWriter w, MemberModel member, string source, string what)
    {
        var name = Parameter(member);
        var raw = "__raw_" + member.Name;
        var literal = SourceWriter.Literal(member.WireName);
        if (member.IsCollection)
        {
            w.Line($"global::Microsoft.Extensions.Primitives.StringValues {raw} = {source};");
            w.Line($"var {name}__list = new global::System.Collections.Generic.List<{member.ParseType}>({raw}.Count);");
            w.Open($"foreach (var __item in {raw})");
            w.Line($"if (__item is null || !{TryParse(member, "__item", "__parsed")}) {{ await {Generated}.ApiBinding.BadRequestAsync(httpContext, {literal}, \"{what}\").ConfigureAwait(false); return; }}");
            w.Line($"{name}__list.Add(__parsed);");
            w.Close();
            w.Line($"var {name} = {name}__list.ToArray();");
            return;
        }

        w.Line($"string? {raw} = {source};");
        if (member.ParseKind == ParseKind.String)
        {
            if (member.IsNullable)
            {
                w.Line($"var {name} = string.IsNullOrEmpty({raw}) ? null : {raw};");
            }
            else
            {
                w.Line($"if (string.IsNullOrEmpty({raw})) {{ await {Generated}.ApiBinding.BadRequestAsync(httpContext, {literal}, \"{what}\").ConfigureAwait(false); return; }}");
                w.Line($"var {name} = {raw};");
            }

            return;
        }

        w.Line($"{member.Type} {name} = default;");
        w.Open($"if (!string.IsNullOrEmpty({raw}))");
        w.Line($"if (!{TryParse(member, raw, "__parsed_" + member.Name)}) {{ await {Generated}.ApiBinding.BadRequestAsync(httpContext, {literal}, \"{what}\").ConfigureAwait(false); return; }}");
        w.Line($"{name} = __parsed_{member.Name};");
        w.Close();
        if (!member.IsNullable)
        {
            w.Line($"else {{ await {Generated}.ApiBinding.BadRequestAsync(httpContext, {literal}, \"{what}\").ConfigureAwait(false); return; }}");
        }
    }

    private static string TryParse(MemberModel member, string value, string result) => member.ParseKind switch
    {
        ParseKind.Enum => $"global::System.Enum.TryParse<{member.ParseType}>({value}, true, out var {result})",
        ParseKind.Uri => $"global::System.Uri.TryCreate({value}, global::System.UriKind.RelativeOrAbsolute, out var {result})",
        ParseKind.Parsable or ParseKind.TryParseWithProvider => $"{member.ParseType}.TryParse({value}, global::System.Globalization.CultureInfo.InvariantCulture, out var {result})",
        ParseKind.TryParse => $"{member.ParseType}.TryParse({value}, out var {result})",
        ParseKind.String => $"({value} is var {result})",
        ParseKind.None => $"({value} is var {result} && false)",
        _ => throw new ArgumentOutOfRangeException(nameof(member)),
    };

    private static IEnumerable<(string Attribute, string Type, string Name, bool HasTryParse, bool IsOptional)> HandlerParameters(OperationModel operation, string service)
    {
        foreach (var member in operation.Members)
        {
            switch (member.Source)
            {
                case BindingSource.Route:
                    yield return ($"[global::Microsoft.AspNetCore.Mvc.FromRoute(Name = {SourceWriter.Literal(member.WireName)})]", member.Type, Parameter(member), member.ParseKind != ParseKind.String, member.IsNullable);
                    break;
                case BindingSource.Query:
                    if (!operation.HasBody) yield return ($"[global::Microsoft.AspNetCore.Mvc.FromQuery(Name = {SourceWriter.Literal(member.WireName)})]", member.Type, Parameter(member), member.ParseKind != ParseKind.String, member.IsNullable);
                    break;
                case BindingSource.Header:
                    yield return ($"[global::Microsoft.AspNetCore.Mvc.FromHeader(Name = {SourceWriter.Literal(member.WireName)})]", member.Type, Parameter(member), member.ParseKind != ParseKind.String, member.IsNullable);
                    break;
                case BindingSource.Service:
                    yield return ("[global::Microsoft.AspNetCore.Mvc.FromServices]", member.Type, Parameter(member), false, false);
                    break;
                case BindingSource.Body:
                case BindingSource.Ignored:
                    break;
                default:
                    break;
            }
        }

        if (operation.HasBody) yield return ("[global::Microsoft.AspNetCore.Mvc.FromBody]", operation.WireType, "__body", false, false);
        yield return ("[global::Microsoft.AspNetCore.Mvc.FromServices]", service, ServerDispatch.SenderParameter, false, false);
        yield return ("", "global::System.Threading.CancellationToken", Ct, false, false);
    }

    // Builds `__request` from the bound parameters: constructor arguments and initializers for GET/DELETE, the body with route/header/service
    // values applied on top for POST/PUT/PATCH.
    private static void WriteRequest(SourceWriter w, OperationModel operation)
    {
        var bound = operation.Members.Where(m => m.Source is BindingSource.Route or BindingSource.Header or BindingSource.Service || !operation.HasBody && m.Source == BindingSource.Query).ToArray();
        if (operation.HasBody)
        {
            w.Line("var __wire = __body;");
            if (bound.Length > 0)
            {
                if (operation.RequestSupportsWith)
                {
                    w.Line($"__wire = __wire with {{ {string.Join(", ", bound.Select(m => $"{m.Name} = {Parameter(m)}"))} }};");
                }
                else
                {
                    foreach (var member in bound) w.Line($"__wire.{member.Name} = {Parameter(member)};");
                }
            }
        }
        else
        {
            var arguments = operation.Members.Where(m => m.ConstructorIndex >= 0).OrderBy(m => m.ConstructorIndex).Select(m => bound.Contains(m) ? Parameter(m) : "default!");
            var initializers = bound.Where(m => m.ConstructorIndex < 0).Select(m => $"{m.Name} = {Parameter(m)}").ToArray();
            w.Line($"var __wire = new {operation.WireType}({string.Join(", ", arguments)}){( initializers.Length > 0 ? " { " + string.Join(", ", initializers) + " }" : "" )};");
        }

        w.Line(operation.InputType is { } ? "var __request = __wire.Create();" : "var __request = __wire;");
    }

    private static void WriteDispatchAndResult(SourceWriter w, HostModel host, ProfileModel profile, OperationModel operation)
    {
        var call = ServerDispatch.Call(profile, operation, "__request", Ct);
        switch (operation.Kind)
        {
            case RequestKind.Stream:
                w.Line($"return new {Generated}.NdjsonResult<{operation.ResponseTypeNotNull}>({call});");
                return;
            case RequestKind.Void:
                w.Line($"await {call}.ConfigureAwait(false);");
                w.Line($"return {Http}.TypedResults.NoContent();");
                return;
            case RequestKind.Unary:
            case RequestKind.Infer:
                break;
            default:
                break;
        }

        w.Line($"var __response = await {call}.ConfigureAwait(false);");
        var value = operation.ResponseIsNullableValueType ? "__response.Value" : "__response";
        var success = operation.SuccessStatusCode switch
        {
            201 when operation.CreatedLocationRoute is { } route => $"{Http}.TypedResults.Created({Location(host, route, operation)}, {value})",
            201 => $"{Http}.TypedResults.Created((string?)null, {value})",
            202 => $"{Http}.TypedResults.Accepted((string?)null, {value})",
            _ => $"{Http}.TypedResults.Ok({value})",
        };
        w.Line(operation.ResponseNullable ? $"return __response is null ? {Http}.TypedResults.NotFound() : {success};" : $"return {success};");
    }

    private static string Location(HostModel host, string route, OperationModel operation)
    {
        var path = "/" + RouteText.Join(host.BaseRoute, route);
        var tokens = RouteText.Tokens(route).ToArray();
        var parts = new List<string>();
        var position = 0;
        for (var index = 0; index < tokens.Length; index++)
        {
            var start = path.IndexOf('{', position);
            var end = path.IndexOf('}', start);
            parts.Add(SourceWriter.Literal(path[position..start]));
            parts.Add($"global::System.Uri.EscapeDataString({Generated}.ApiFormat.Value(__response.{operation.CreatedLocationTokens[index]}))");
            position = end + 1;
        }

        parts.Add(SourceWriter.Literal(path[position..]));
        return string.Join(" + ", parts.Where(p => p != "\"\""));
    }

    private static (string Type, bool IsAsync) ReturnType(ProfileModel profile, OperationModel operation)
    {
        switch (operation.Kind)
        {
            case RequestKind.Stream:
                var stream = $"{Generated}.NdjsonResult<{operation.ResponseTypeNotNull}>";
                // A stream whose call awaits (Foundatio's InvokeAsync<IAsyncEnumerable<T>>) is produced asynchronously.
                return ServerDispatch.Call(profile, operation, "__request", Ct).StartsWith("await ", StringComparison.Ordinal)
                    ? ($"global::System.Threading.Tasks.Task<{stream}>", true)
                    : (stream, false);
            case RequestKind.Void:
                return ($"global::System.Threading.Tasks.Task<{Results}.NoContent>", true);
            case RequestKind.Unary:
            case RequestKind.Infer:
                break;
            default:
                break;
        }

        var success = operation.SuccessStatusCode switch
        {
            201 => $"{Results}.Created<{operation.ResponseTypeNotNull}>",
            202 => $"{Results}.Accepted<{operation.ResponseTypeNotNull}>",
            _ => $"{Results}.Ok<{operation.ResponseTypeNotNull}>",
        };
        return (operation.ResponseNullable ? $"global::System.Threading.Tasks.Task<{Results}.Results<{success}, {Results}.NotFound>>" : $"global::System.Threading.Tasks.Task<{success}>", true);
    }

    private static string Unwrap(string type)
    {
        const string task = "global::System.Threading.Tasks.Task<";
        return type.StartsWith(task, StringComparison.Ordinal) ? type.Substring(task.Length, type.Length - task.Length - 1) : type;
    }

    private static string Verb(HttpVerb verb) => verb switch
    {
        HttpVerb.Get => "GET",
        HttpVerb.Post => "POST",
        HttpVerb.Put => "PUT",
        HttpVerb.Patch => "PATCH",
        HttpVerb.Delete => "DELETE",
        _ => throw new ArgumentOutOfRangeException(nameof(verb)),
    };

    private static string KindName(RequestKind kind) => kind switch
    {
        RequestKind.Unary => "unary",
        RequestKind.Void => "void",
        RequestKind.Stream => "stream",
        RequestKind.Infer => "unknown",
        _ => throw new ArgumentOutOfRangeException(nameof(kind)),
    };

    private static string Parameter(MemberModel member) => "@" + Naming.CamelCase(member.Name);


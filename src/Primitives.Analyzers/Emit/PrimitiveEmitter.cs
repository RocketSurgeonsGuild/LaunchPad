using Rocket.Surgery.LaunchPad.Primitives.Analyzers.Model;

namespace Rocket.Surgery.LaunchPad.Primitives.Analyzers.Emit;

/// <summary>
///     Writes the part of a domain primitive the generator completes.
/// </summary>
internal static class PrimitiveEmitter
{
    public static string Emit(PrimitiveModel model)
    {
        var writer = new SourceWriter();
        writer.Line("// <auto-generated>");
        writer.Line("//     Written by the domain primitive generator of Rocket.Surgery.LaunchPad.Primitives (a port of dotnet-domain-primitives, MIT).");
        writer.Line("// </auto-generated>");
        writer.Line("#nullable enable");
        writer.Line("#pragma warning disable CS1591, CS0618, CS0612");
        writer.Line();
        if (model.Namespace is not null) writer.Open($"namespace {model.Namespace}");
        foreach (var containing in model.ContainingTypes)
        {
            writer.Open(containing);
        }

        switch (model.Shape)
        {
            case PrimitiveShape.SmartEnum when model.IsStruct:
                StructSmartEnumEmitter.Emit(writer, model);
                break;
            case PrimitiveShape.SmartEnum:
                SmartEnumEmitter.Emit(writer, model);
                break;
            case PrimitiveShape.ValueObject:
                ValueObjectEmitter.Emit(writer, model);
                break;
            case PrimitiveShape.String:
            case PrimitiveShape.Numeric:
            case PrimitiveShape.Date:
            case PrimitiveShape.StrongId:
            default:
                SingleValueEmitter.Emit(writer, model);
                break;
        }

        foreach (var _ in model.ContainingTypes)
        {
            writer.Close();
        }

        if (model.Namespace is not null) writer.Close();
        return writer.ToString();
    }

    /// <summary>
    ///     The declaration of the domain primitive: <c>readonly partial record struct X</c> or <c>sealed partial record X</c>.
    /// </summary>
    public static string Declaration(PrimitiveModel model) => model.IsStruct ? $"readonly partial record struct {model.Name}" : $"sealed partial record {model.Name}";

    /// <summary>
    ///     The type of an out parameter that holds the domain primitive when the method returns true.
    /// </summary>
    public static string OutResult(PrimitiveModel model) => model.IsStruct ? model.Name : model.Name + "?";

    public static void TypeAttributes(SourceWriter writer, PrimitiveModel model, bool typeConverter = true)
    {
        writer.Line($"[{Names.GeneratedCode}]");
        writer.Line("[global::System.Diagnostics.CodeAnalysis.ExcludeFromCodeCoverage]");
        writer.Line("[global::System.Diagnostics.DebuggerDisplay(\"{ToString(),nq}\")]");
        writer.Line($"[global::System.Text.Json.Serialization.JsonConverter(typeof({model.Name}.{model.Name}JsonConverter))]");
        if (typeConverter) writer.Line($"[global::System.ComponentModel.TypeConverter(typeof({model.Name}.{model.Name}TypeConverter))]");
    }

    /// <summary>
    ///     Throws the exception for a rejected value: <c>LaunchPadPrimitivesExceptionType</c>, or DomainPrimitiveValidationException.
    /// </summary>
    public static void Fail(SourceWriter writer, PrimitiveModel model)
    {
        writer.Line("private static global::System.Exception Fail(" + Names.Error + " error) =>");
        writer.Indent();
        writer.Line(
            model.ExceptionType is { } exception
                ? $"new {exception}(error.Message ?? error.Code ?? \"The value is not valid.\");"
                : $"new {Names.Exception}(error);"
        );
        writer.Outdent();
        writer.Line();
    }

    public static void RecordSuccess(SourceWriter writer)
    {
        writer.Line($"{Names.Instrumentation}.RecordValidationSuccess(PrimitiveName);");
        writer.Line($"{Names.Instrumentation}.RecordCreation(PrimitiveName);");
    }

    public static void RecordFailure(SourceWriter writer, string error = "validationError") =>
        writer.Line($"{Names.Instrumentation}.RecordValidationFailure(PrimitiveName, {error});");

    /// <summary>
    ///     An expression that reads a value of <paramref name="value" /> from <c>reader</c>.
    /// </summary>
    public static string ReadJson(ValueTypeInfo value) => value.HasBuiltInJsonConverter
        ? $"{Names.JsonMetadata}.JsonMetadataServices.{value.MetadataName}Converter.Read(ref reader, typeof({value.Display}), options){( value.IsString ? "!" : "" )}"
        : $"{Names.Json}.JsonSerializer.Deserialize(ref reader, ({Names.JsonMetadata}.JsonTypeInfo<{value.Display}>)options.GetTypeInfo(typeof({value.Display})))!";

    /// <summary>
    ///     A statement that writes <paramref name="expression" />, a value of <paramref name="value" />, to <c>writer</c>.
    /// </summary>
    public static string WriteJson(ValueTypeInfo value, string expression) => value.HasBuiltInJsonConverter
        ? $"{Names.JsonMetadata}.JsonMetadataServices.{value.MetadataName}Converter.Write(writer, {expression}, options);"
        : $"{Names.Json}.JsonSerializer.Serialize(writer, {expression}, ({Names.JsonMetadata}.JsonTypeInfo<{value.Display}>)options.GetTypeInfo(typeof({value.Display})));";
}

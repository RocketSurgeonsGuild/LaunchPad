using Microsoft.CodeAnalysis;

namespace Rocket.Surgery.LaunchPad.Api.Generators;

/// <summary>
///     Generates an MVC action for every operation a controller host lists, and fills in what the host doesn't declare: <c>[ApiController]</c>,
///     <c>[Route("{RoutePrefix}/{Group}")]</c> and the <c>ControllerBase</c> base class.
/// </summary>
/// <remarks>
///     <para>
///         Actions return MVC results (<c>OkObjectResult</c>, <c>CreatedResult</c>, …), so responses go through MVC's formatters and JSON options
///         like a hand-written controller's, and each action carries <c>[ProducesResponseType]</c> for ApiExplorer and OpenAPI.
///     </para>
///     <para>
///         The mediator is resolved inside the action rather than taken as a parameter: some senders are internal to the project (ZeroAlloc),
///         and a public action can't take an internal parameter type.
///     </para>
/// </remarks>
[Generator]
public sealed class ControllerGenerator : IIncrementalGenerator
{
    private const string Mvc = "global::Microsoft.AspNetCore.Mvc";
    private const string Ct = "__cancellationToken";
    private const string Generated = "global::Rocket.Surgery.LaunchPad.Api.Generated.Mvc";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(
            static output =>
            {
                HostPipeline.EmitMarker(output, HostKind.Controller);
                output.AddSource("Rocket.Surgery.LaunchPad.Api.Generated.ControllerHelpers.g.cs", ControllerHelpers);
            }
        );

        var hosts = HostPipeline.Hosts(context, HostKind.Controller);
        context.RegisterSourceOutput(hosts, static (output, models) => Emit(output, models));
    }

    private static void Emit(SourceProductionContext output, EquatableArray<HostModel> hosts)
    {
        // Endpoint names are global to an application: an operation listed on two hosts gets its host noun in front.
        var duplicateNames = hosts.SelectMany(h => h.Operations.Select(o => o.EndpointName)).GroupBy(n => n).Where(g => g.Count() > 1).Select(g => g.Key).ToHashSet();
        foreach (var host in hosts)
        {
            foreach (var diagnostic in host.Diagnostics) output.ReportDiagnostic(diagnostic.ToDiagnostic());
            if (host.Profile is null) continue;
            output.AddSource(host.FullyQualifiedName.Replace("global::", "") + ".Controller.g.cs", Write(host, host.Profile, duplicateNames, output));
        }

        foreach (var duplicate in hosts.SelectMany(h => h.Operations.Select(o => (Host: h, Operation: o)))
                                       .GroupBy(x => (x.Operation.Verb, Route: "/" + RouteText.Join(x.Host.BaseRoute, x.Operation.Route).ToLowerInvariant()))
                                       .Where(g => g.Select(x => x.Host.Name).Distinct().Count() > 1))
        {
            var items = duplicate.ToArray();
            output.ReportDiagnostic(
                DiagnosticInfo.Create(ApiDiagnostics.DuplicateRoute, items[1].Operation.Location, ServerEmit.Verb(duplicate.Key.Verb), duplicate.Key.Route, items[0].Host.Name, items[1].Host.Name)
                              .ToDiagnostic()
            );
        }
    }

    private static string Write(HostModel host, ProfileModel profile, HashSet<string> duplicateNames, SourceProductionContext output)
    {
        var w = new SourceWriter();
        w.Line("// <auto-generated/>").Line("#nullable enable").Line("#pragma warning disable CS1591").Line();
        if (host.Namespace is { } ns) w.Open($"namespace {ns}");

        if (!host.DeclaresApiController) w.Line($"[{Mvc}.ApiController]");
        if (host.DeclaredRoute is null) w.Line($"[{Mvc}.Route({SourceWriter.Literal(host.BaseRoute)})]");
        w.Line($"[global::Microsoft.AspNetCore.Http.Tags({SourceWriter.Literal(Naming.HostNoun(host.Name))})]");
        w.Line($"[global::System.CodeDom.Compiler.GeneratedCode(\"Rocket.Surgery.LaunchPad.Api.Controllers\", \"{typeof(ControllerGenerator).Assembly.GetName().Version}\")]");
        w.Open($"{host.Accessibility} partial class {host.Name}{( host.DeclaresBaseType ? "" : $" : {Mvc}.ControllerBase" )}");

        var first = true;
        foreach (var operation in host.Operations)
        {
            if (ServerDispatch.ServiceType(profile, operation) is not { } service)
            {
                output.ReportDiagnostic(
                    DiagnosticInfo.Create(ApiDiagnostics.FeatureSkipped, operation.Location, operation.Name, host.Name, $"the {profile.Name} profile cannot dispatch {ServerEmit.KindName(operation.Kind)} operations")
                                  .ToDiagnostic()
                );
                continue;
            }

            if (!first) w.Line();
            first = false;
            WriteAction(w, host, profile, operation, service, duplicateNames.Contains(operation.EndpointName));
        }

        w.Close();
        if (host.Namespace is { }) w.Close();
        return w.ToString();
    }

    private static void WriteAction(SourceWriter w, HostModel host, ProfileModel profile, OperationModel operation, string service, bool prefixName)
    {
        var route = operation.Route.Trim('/');
        w.Line($"/// <summary>Handles <c>{ServerEmit.Verb(operation.Verb)} /{RouteText.Join(host.BaseRoute, operation.Route)}</c> by sending <see cref=\"{Cref(operation.RequestType)}\" />.</summary>");
        w.Line($"[{Mvc}.Http{operation.Verb}({SourceWriter.Literal(route)})]");
        var name = prefixName ? Naming.HostNoun(host.Name) + operation.EndpointName : operation.EndpointName;
        w.Line($"[global::Microsoft.AspNetCore.Routing.EndpointName({SourceWriter.Literal(name)})]");
        if (operation.Summary is { } summary) w.Line($"[global::Microsoft.AspNetCore.Http.EndpointSummary({SourceWriter.Literal(summary)})]");
        if (operation.Description is { } description) w.Line($"[global::Microsoft.AspNetCore.Http.EndpointDescription({SourceWriter.Literal(description)})]");
        if (operation.Tags.Length > 0) w.Line($"[global::Microsoft.AspNetCore.Http.Tags({string.Join(", ", operation.Tags.Select(SourceWriter.Literal))})]");
        foreach (var policy in operation.Policies) w.Line($"[global::Microsoft.AspNetCore.Authorization.Authorize(Policy = {SourceWriter.Literal(policy)})]");
        if (operation.Roles.Length > 0 || operation.AuthenticationSchemes.Length > 0)
        {
            var settings = new List<string>();
            if (operation.Roles.Length > 0) settings.Add($"Roles = {SourceWriter.Literal(string.Join(",", operation.Roles))}");
            if (operation.AuthenticationSchemes.Length > 0) settings.Add($"AuthenticationSchemes = {SourceWriter.Literal(string.Join(",", operation.AuthenticationSchemes))}");
            w.Line($"[global::Microsoft.AspNetCore.Authorization.Authorize({string.Join(", ", settings)})]");
        }

        if (operation.AllowAnonymous) w.Line("[global::Microsoft.AspNetCore.Authorization.AllowAnonymous]");
        foreach (var produces in Produces(operation)) w.Line(produces);

        var parameters = ServerEmit.HandlerParameters(operation, null, Ct).Select(p =>  $"{p.Attribute} {p.Type} {p.Name}" .TrimStart());
        // A stream is returned synchronously unless producing it awaits (Foundatio's InvokeAsync<IAsyncEnumerable<T>>, Immediate.Handlers).
        var streamAwaits = ServerDispatch.Call(profile, operation, "__request", Ct).StartsWith("await ", StringComparison.Ordinal);
        var returnType = operation.Kind switch
        {
            RequestKind.Unary or RequestKind.Infer => $"async global::System.Threading.Tasks.Task<{Mvc}.ActionResult<{operation.ResponseTypeNotNull}>>",
            RequestKind.Void => $"async global::System.Threading.Tasks.Task<{Mvc}.IActionResult>",
            RequestKind.Stream => streamAwaits ? $"async global::System.Threading.Tasks.Task<{Mvc}.IActionResult>" : $"{Mvc}.IActionResult",
            _ => throw new ArgumentOutOfRangeException(nameof(operation)),
        };
        w.Open($"public {returnType} {operation.Name}({string.Join(", ", parameters)})");
        ServerEmit.WriteRequest(w, operation);
        w.Line($"var {ServerDispatch.SenderParameter} = global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions.GetRequiredService<{service}>(HttpContext.RequestServices);");
        WriteDispatchAndResult(w, host, profile, operation);
        w.Close();
    }

    // [ProducesResponseType] for every status the action can answer, so ApiExplorer describes it without reading the body.
    private static IEnumerable<string> Produces(OperationModel operation)
    {
        var json = "\"application/json\"";
        switch (operation.Kind)
        {
            case RequestKind.Stream:
                yield return $"[{Mvc}.ProducesResponseType(typeof(global::System.Collections.Generic.IAsyncEnumerable<{operation.ResponseTypeNotNull}>), 200, \"application/x-ndjson\")]";
                break;
            case RequestKind.Void:
                yield return $"[{Mvc}.ProducesResponseType(204)]";
                break;
            case RequestKind.Unary:
            case RequestKind.Infer:
                yield return $"[{Mvc}.ProducesResponseType(typeof({operation.ResponseTypeNotNull}), {operation.SuccessStatusCode}, {json})]";
                if (operation.ResponseNullable) yield return $"[{Mvc}.ProducesResponseType(404)]";
                break;
            default:
                break;
        }

        // [ApiController] answers 400 with ValidationProblemDetails when a value can't be bound.
        if (operation.HasBody || operation.Members.Any(m => m.Source is BindingSource.Route or BindingSource.Query or BindingSource.Header))
        {
            yield return $"[{Mvc}.ProducesResponseType(typeof({Mvc}.ValidationProblemDetails), 400, \"application/problem+json\")]";
        }
    }

    private static void WriteDispatchAndResult(SourceWriter w, HostModel host, ProfileModel profile, OperationModel operation)
    {
        var call = ServerDispatch.Call(profile, operation, "__request", Ct);
        switch (operation.Kind)
        {
            case RequestKind.Stream:
                w.Line($"return new {Generated}.NdjsonResult<{operation.ResponseTypeNotNull}>({call});");
                return;
            case RequestKind.Void:
                w.Line($"await {call}.ConfigureAwait(false);");
                w.Line($"return new {Mvc}.NoContentResult();");
                return;
            case RequestKind.Unary:
            case RequestKind.Infer:
                break;
            default:
                break;
        }

        w.Line($"var __response = await {call}.ConfigureAwait(false);");
        var value = operation.ResponseIsNullableValueType ? "__response.Value" : "__response";
        var success = operation.SuccessStatusCode switch
        {
            201 when operation.CreatedLocationRoute is { } route => $"new {Mvc}.CreatedResult({ServerEmit.Location(host.BaseRoute, route, operation, Generated)}, {value})",
            201 => $"new {Mvc}.ObjectResult({value}) {{ StatusCode = 201 }}",
            202 => $"new {Mvc}.AcceptedResult((string?)null, {value})",
            _ => $"new {Mvc}.OkObjectResult({value})",
        };
        w.Line(operation.ResponseNullable ? $"return __response is null ? new {Mvc}.NotFoundResult() : {success};" : $"return {success};");
    }

    private static string Cref(string type) => type.Replace("global::", "").Replace('<', '{').Replace('>', '}');

    private const string ControllerHelpers = """
// <auto-generated/>
#nullable enable
#pragma warning disable
namespace Rocket.Surgery.LaunchPad.Api.Generated.Mvc
{
    /// <summary>Formats a route value: invariant culture, enums by name, booleans in lowercase.</summary>
    [global::Microsoft.CodeAnalysis.EmbeddedAttribute]
    internal static class ApiFormat
    {
        public static string Value(object? value) => value switch
        {
            null => "",
            bool b => b ? "true" : "false",
            global::System.Enum e => e.ToString(),
            global::System.IFormattable f => f.ToString(null, global::System.Globalization.CultureInfo.InvariantCulture),
            _ => value.ToString() ?? "",
        };
    }

    /// <summary>Writes a stream operation as newline-delimited JSON with MVC's JSON options, flushing after every item.</summary>
    [global::Microsoft.CodeAnalysis.EmbeddedAttribute]
    internal sealed class NdjsonResult<T> : global::Microsoft.AspNetCore.Mvc.IActionResult
    {
        private static readonly byte[] NewLine = { (byte)'\n' };
        private readonly global::System.Collections.Generic.IAsyncEnumerable<T> _items;

        public NdjsonResult(global::System.Collections.Generic.IAsyncEnumerable<T> items) => _items = items;

        public async global::System.Threading.Tasks.Task ExecuteResultAsync(global::Microsoft.AspNetCore.Mvc.ActionContext context)
        {
            var httpContext = context.HttpContext;
            var options = global::Microsoft.Extensions.DependencyInjection.ServiceProviderServiceExtensions
                         .GetRequiredService<global::Microsoft.Extensions.Options.IOptions<global::Microsoft.AspNetCore.Mvc.JsonOptions>>(httpContext.RequestServices)
                         .Value.JsonSerializerOptions;
            var typeInfo = (global::System.Text.Json.Serialization.Metadata.JsonTypeInfo<T>)options.GetTypeInfo(typeof(T));
            var cancellationToken = httpContext.RequestAborted;
            httpContext.Response.ContentType = "application/x-ndjson";
            var body = httpContext.Response.Body;
            await foreach (var item in global::System.Threading.Tasks.TaskAsyncEnumerableExtensions.WithCancellation(_items, cancellationToken).ConfigureAwait(false))
            {
                await global::System.Text.Json.JsonSerializer.SerializeAsync(body, item, typeInfo, cancellationToken).ConfigureAwait(false);
                await body.WriteAsync(NewLine, cancellationToken).ConfigureAwait(false);
                await body.FlushAsync(cancellationToken).ConfigureAwait(false);
            }
        }
    }
}
""";
}

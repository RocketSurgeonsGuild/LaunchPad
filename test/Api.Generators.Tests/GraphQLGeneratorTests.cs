namespace Api.Generators.Tests;

public class GraphQLGeneratorTests() : GeneratorTest()
{
    [Test]
    [Arguments(Mediator.MediatR)]
    [Arguments(Mediator.Mediator)]
    [Arguments(Mediator.ChannelMediator)]
    [Arguments(Mediator.ImmediateHandlers)]
    [Arguments(Mediator.Foundatio)]
    [Arguments(Mediator.ZeroAlloc)]
    public async Task Should_Generate_Mutations(Mediator mediator)
    {
        var contracts = await CompileContracts(mediator, Contracts.For(mediator));
        var result = await GraphQLServer(mediator, contracts).AddSources(Contracts.MutationHost).Build().GenerateAsync(TestContext.CancellationToken);

        // ZeroAlloc's IMediator is generated by ZeroAlloc's own generator, which doesn't run here.
        if (mediator != Mediator.ZeroAlloc) AssertCompiles(result);
        await Verify(result).UseParameters(mediator);
    }

    [Test]
    [Arguments(Mediator.MediatR)]
    [Arguments(Mediator.Mediator)]
    [Arguments(Mediator.ChannelMediator)]
    [Arguments(Mediator.ImmediateHandlers)]
    [Arguments(Mediator.Foundatio)]
    [Arguments(Mediator.ZeroAlloc)]
    public async Task Should_Generate_A_Client(Mediator mediator)
    {
        var contracts = await CompileContracts(mediator, Contracts.For(mediator));
        var result = await GraphQLClient(mediator, contracts).AddSources(Contracts.GraphQLClientHost).Build().GenerateAsync(TestContext.CancellationToken);

        if (mediator != Mediator.ZeroAlloc) AssertCompiles(result);
        await Verify(result).UseParameters(mediator);
    }

    [Test]
    [Arguments("LPAD1019", "[Operation<GetRocket.Request>] public partial class RocketsMutations;")]
    [Arguments("LPAD1015", "[Operation<ListRockets.Request>(Name = \"CreateRockets\")] public partial class RocketsMutations;")]
    [Arguments("LPAD1009", "[Operation<CreateRocket.Request>] public partial class RocketsMutations; [Operation<CreateRocket.Request>] public partial class FleetMutations;")]
    [Arguments("LPAD1017", "[Operation<GetRocket.Request>] public partial class RocketsQueries;")]
    public async Task Should_Report(string id, string source)
    {
        var contracts = await CompileContracts(Mediator.MediatR, Contracts.For(Mediator.MediatR));
        var result = await GraphQLServer(Mediator.MediatR, contracts)
                          .AddSources($"using Rocket.Surgery.LaunchPad.Api;\nusing Sample.Contracts.Rockets;\n\n{source}\n")
                          .Build()
                          .GenerateAsync(TestContext.CancellationToken);

        DiagnosticIds(result).ShouldContain(id);
    }
}

namespace Api.Generators.Tests;

public class GrpcGeneratorTests() : GeneratorTest()
{
    [Test]
    [Arguments(Mediator.MediatR)]
    [Arguments(Mediator.Mediator)]
    [Arguments(Mediator.ChannelMediator)]
    [Arguments(Mediator.ImmediateHandlers)]
    [Arguments(Mediator.Foundatio)]
    [Arguments(Mediator.ZeroAlloc)]
    public async Task Should_Generate_A_Service(Mediator mediator)
    {
        var contracts = await CompileContracts(mediator, Contracts.For(mediator));
        var result = await GrpcServer(mediator, contracts).AddSources(Contracts.GrpcServiceHost).Build().GenerateAsync(TestContext.CancellationToken);

        // ZeroAlloc's IMediator is generated by ZeroAlloc's own generator, which doesn't run here.
        if (mediator != Mediator.ZeroAlloc) AssertCompiles(result);
        await Verify(result).UseParameters(mediator);
    }

    [Test]
    [Arguments(Mediator.MediatR)]
    [Arguments(Mediator.Mediator)]
    [Arguments(Mediator.ChannelMediator)]
    [Arguments(Mediator.ImmediateHandlers)]
    [Arguments(Mediator.Foundatio)]
    [Arguments(Mediator.ZeroAlloc)]
    public async Task Should_Generate_A_Client(Mediator mediator)
    {
        var contracts = await CompileContracts(mediator, Contracts.For(mediator));
        var result = await GrpcClient(mediator, contracts).AddSources(Contracts.GrpcClientHost).Build().GenerateAsync(TestContext.CancellationToken);

        if (mediator != Mediator.ZeroAlloc) AssertCompiles(result);
        await Verify(result).UseParameters(mediator);
    }

    [Test]
    public async Task Should_Report_Types_Without_A_Contract()
    {
        // The shared contracts are plain records: protobuf-net can't carry them without [DataContract] or [ProtoContract].
        var contracts = await CompileContracts(Mediator.MediatR, Contracts.For(Mediator.MediatR));
        var result = await GrpcServer(Mediator.MediatR, contracts).AddSources(Contracts.GrpcServiceHost).Build().GenerateAsync(TestContext.CancellationToken);

        var reported = result.Results.Values.SelectMany(r => r.Diagnostics).Where(d => d.Id == "LPAD1014").Select(d => d.GetMessage(System.Globalization.CultureInfo.InvariantCulture)).ToArray();
        reported.ShouldContain(m => m.StartsWith("Sample.Contracts.Rockets.GetRocket.Request ", StringComparison.Ordinal));
        reported.ShouldContain(m => m.StartsWith("Sample.Contracts.Rockets.RocketModel ", StringComparison.Ordinal));
        reported.ShouldNotContain(m => m.Contains("Unit", StringComparison.Ordinal));
    }
}

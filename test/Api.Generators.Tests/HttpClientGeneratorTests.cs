using System.Text.RegularExpressions;
using Rocket.Surgery.Extensions.Testing.SourceGenerators;

namespace Api.Generators.Tests;

public class HttpClientGeneratorTests() : GeneratorTest()
{
    [Test]
    [Arguments(Mediator.MediatR)]
    [Arguments(Mediator.Mediator)]
    [Arguments(Mediator.ChannelMediator)]
    [Arguments(Mediator.ImmediateHandlers)]
    [Arguments(Mediator.Foundatio)]
    [Arguments(Mediator.ZeroAlloc)]
    public async Task Should_Generate_Client_And_Handlers(Mediator mediator)
    {
        var contracts = await CompileContracts(mediator, Contracts.For(mediator));
        var result = await Client(mediator, contracts).AddSources(Contracts.ClientHost).Build().GenerateAsync(TestContext.CancellationToken);

        // ZeroAlloc's MediatorService half is generated by ZeroAlloc's own generator, which doesn't run here.
        if (mediator != Mediator.ZeroAlloc) AssertCompiles(result);
        await Verify(result).UseParameters(mediator);
    }

    [Test]
    public async Task Should_Skip_Handlers_When_Asked()
    {
        var contracts = await CompileContracts(Mediator.MediatR, Contracts.For(Mediator.MediatR));
        var result = await Client(Mediator.MediatR, contracts)
                          .AddSources(
                               """
                               using Rocket.Surgery.LaunchPad.Api;
                               using Sample.Contracts.Rockets;

                               [OperationHost(ClientName = "Fleet", Handlers = false, Version = "2.0", JsonOptions = JsonOptionsPreset.Default)]
                               [Operation<GetRocket.Request>]
                               [Operation<EditRocket.Request>(Handlers = true)]
                               public partial class FleetClient;
                               """
                           )
                          .Build()
                          .GenerateAsync(TestContext.CancellationToken);

        AssertCompiles(result);
        await Verify(result);
    }

    [Test]
    [Arguments(Mediator.Mediator, "|Mediator.SourceGenerator|")]
    [Arguments(Mediator.Foundatio, "|Foundatio.Mediator|")]
    [Arguments(Mediator.ZeroAlloc, "|")]
    public async Task Should_Report_A_Client_Host_In_The_Wrong_Project(Mediator mediator, string mediatorGenerators)
    {
        var result = await ClientWithGenerators(mediator, mediatorGenerators);

        DiagnosticIds(result).ShouldContain("LPAD1012");
        await Verify(Messages(result, "LPAD1012")).UseParameters(mediator);
    }

    [Test]
    [Arguments(Mediator.MediatR, "|Mediator.SourceGenerator|")]
    [Arguments(Mediator.Mediator, "|")]
    [Arguments(Mediator.Foundatio, "|ZeroAlloc.Mediator.Generator|")]
    [Arguments(Mediator.ZeroAlloc, "|ZeroAlloc.Mediator.Generator|")]
    public async Task Should_Accept_A_Client_Host_In_The_Right_Project(Mediator mediator, string mediatorGenerators)
    {
        var result = await ClientWithGenerators(mediator, mediatorGenerators);

        DiagnosticIds(result).ShouldNotContain("LPAD1012");
    }

    [Test]
    [Arguments(
        Mediator.MediatR,
        "public sealed class Handler : MediatR.IRequestHandler<Request, RocketModel?> { public System.Threading.Tasks.Task<RocketModel?> Handle(Request request, System.Threading.CancellationToken cancellationToken) => throw null!; }"
    )]
    [Arguments(Mediator.Foundatio, "public sealed class Handler { public RocketModel? Handle(Request request) => null; }")]
    public async Task Should_Report_A_Hand_Written_Handler(Mediator mediator, string handler)
    {
        // The server's handler, declared next to the request the way LaunchPad's samples do it, in a contracts project the client references.
        var source = Regex.Replace(Contracts.For(mediator), @"public static class GetRocket\s*\{", m => m.Value + "\n" + handler + "\n");
        source.ShouldContain(handler);
        var contracts = await CompileContracts(mediator, source);
        var result = await Client(mediator, contracts).AddSources(Contracts.ClientHost).Build().GenerateAsync(TestContext.CancellationToken);

        DiagnosticIds(result).ShouldContain("LPAD1013");
        await Verify(Messages(result, "LPAD1013")).UseParameters(mediator);
    }

    private async Task<GeneratorTestResults> ClientWithGenerators(Mediator mediator, string mediatorGenerators)
    {
        var contracts = await CompileContracts(mediator, Contracts.For(mediator));
        return await Client(mediator, contracts)
                    .AddGlobalOption("build_property.LaunchPadApiMediatorGenerators", mediatorGenerators)
                    .AddSources(Contracts.ClientHost)
                    .Build()
                    .GenerateAsync(TestContext.CancellationToken);
    }

    private static string[] Messages(GeneratorTestResults result, string id) =>
        [.. result.Results.Values.SelectMany(r => r.Diagnostics).Where(d => d.Id == id).Select(d => d.GetMessage(System.Globalization.CultureInfo.InvariantCulture))];

    [Test]
    [Arguments("LPAD1018", "[Operation<GetRocket.Request>] public partial class RocketsClient; [Operation<GetRocket.Request>] public partial class FleetClient;")]
    [Arguments("LPAD1022", "[Operation<GetRocket.Request>] public partial class RocketsClient { public RocketsClient() { } }")]
    public async Task Should_Report(string id, string source)
    {
        var contracts = await CompileContracts(Mediator.MediatR, Contracts.For(Mediator.MediatR));
        var result = await Client(Mediator.MediatR, contracts)
                          .AddSources($"using Rocket.Surgery.LaunchPad.Api;\nusing Sample.Contracts.Rockets;\n\n{source}\n")
                          .Build()
                          .GenerateAsync(TestContext.CancellationToken);

        DiagnosticIds(result).ShouldContain(id);
        await Verify(result).UseParameters(id);
    }
}

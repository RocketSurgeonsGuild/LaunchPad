using Rocket.Surgery.Extensions.Testing.SourceGenerators;

namespace Api.Generators.Tests;

public class MinimalApiGeneratorTests() : GeneratorTest()
{
    [Test]
    [Arguments(Mediator.MediatR)]
    [Arguments(Mediator.Mediator)]
    [Arguments(Mediator.ChannelMediator)]
    [Arguments(Mediator.ImmediateHandlers)]
    [Arguments(Mediator.Foundatio)]
    [Arguments(Mediator.ZeroAlloc)]
    public async Task Should_Generate_Rest_Endpoints(Mediator mediator)
    {
        var contracts = await CompileContracts(mediator, Contracts.For(mediator));
        var result = await Server(mediator, contracts).AddSources(Contracts.ServerHost).Build().GenerateAsync(TestContext.CancellationToken);

        // ZeroAlloc's IMediator is generated by ZeroAlloc's own generator, which doesn't run here.
        if (mediator != Mediator.ZeroAlloc) AssertCompiles(result);
        await Verify(result).UseParameters(mediator);
    }

    [Test]
    public async Task Should_Apply_Operation_And_Host_Settings()
    {
        var contracts = await CompileContracts(
            Mediator.MediatR,
            """
            #nullable enable
            using MediatR;
            using Rocket.Surgery.LaunchPad.Api;

            namespace Sample.Contracts
            {
                public enum RocketType { Falcon, Starship }
                public sealed record RocketModel(System.Guid Id, string Name);

                public static class SearchRockets
                {
                    [ApiOperation(Path = "search", Tags = new[] { "search" }, Description = "Find rockets")]
                    public sealed record Request : IRequest<RocketModel[]>
                    {
                        [ApiQuery(Name = "q")] public string? Text { get; init; }
                        public RocketType[]? Types { get; init; }
                        [ApiHeader(Name = "X-Tenant")] public string? Tenant { get; init; }
                        [ApiIgnore] public object? Internal { get; init; }
                    }
                }

                public static class LaunchRocket
                {
                    [ApiOperation(Verb = "POST", SuccessStatusCode = 202)]
                    public sealed record Request(System.Guid Id) : IRequest<RocketModel>;
                }
            }
            """
        );
        var result = await Server(Mediator.MediatR, contracts)
                          .AddSources(
                               """
                               using Rocket.Surgery.LaunchPad.Api;
                               using Sample.Contracts;

                               [OperationHost(Group = "fleet", RoutePrefix = "api/v2")]
                               [Operation<SearchRockets.Request>(Policy = new[] { "rockets.read" }, Summary = "Search")]
                               [Operation<LaunchRocket.Request>(Route = "{id}/launch", Roles = new[] { "pilot" }, AuthenticationSchemes = new[] { "Bearer" })]
                               public static partial class RocketsEndpoints
                               {
                                   static partial void ConfigureLaunchRocket(Microsoft.AspNetCore.Builder.IEndpointConventionBuilder endpoint) { }
                               }
                               """
                           )
                          .Build()
                          .GenerateAsync(TestContext.CancellationToken);

        AssertCompiles(result);
        await Verify(result);
    }

    [Test]
    public async Task Should_Bind_A_Transport_Input()
    {
        var contracts = await CompileContracts(
            Mediator.MediatR,
            """
            #nullable enable
            using MediatR;

            namespace Sample.Contracts
            {
                public sealed record RocketModel(System.Guid Id, string Name);
                public static class PatchRocket { public sealed record Request(System.Guid Id, string? Name) : IRequest<RocketModel>; }
                public sealed record PatchRocketInput(System.Guid Id, string? Name)
                {
                    public PatchRocket.Request Create() => new(Id, Name);
                }
            }
            """
        );
        var result = await Server(Mediator.MediatR, contracts)
                          .AddSources(
                               """
                               using Rocket.Surgery.LaunchPad.Api;
                               using Sample.Contracts;

                               [Operation<PatchRocket.Request>(Input = typeof(PatchRocketInput))]
                               public static partial class RocketsEndpoints;
                               """
                           )
                          .Build()
                          .GenerateAsync(TestContext.CancellationToken);

        AssertCompiles(result);
        await Verify(result);
    }

    [Test]
    [Arguments("LPAD1003", "[Operation<GetRocket.Request>(Route = \"{rocketId}\")]", "public static partial class RocketsEndpoints;")]
    [Arguments("LPAD1008", "[Operation<GetRocket.Request>][Operation<FindRocket.Request>]", "public static partial class RocketsEndpoints;")]
    [Arguments("LPAD1007", "[Operation<SearchRockets.Request>]", "public static partial class RocketsEndpoints;")]
    [Arguments("LPAD1010", "[Operation<GetRocket.Request>]", "public partial class RocketsEndpoints;")]
    [Arguments("LPAD1017", "[Operation<GetRocket.Request>]", "public static partial class Rockets;")]
    [Arguments("LPAD1020", "[Operation<GetRocket.Request>(Input = typeof(RocketModel))]", "public static partial class RocketsEndpoints;")]
    [Arguments("LPAD1023", "[Operation<CreateRocket.Request>]", "public static partial class RocketsEndpoints;")]
    public async Task Should_Report(string id, string attributes, string declaration)
    {
        var contracts = await CompileContracts(
            Mediator.MediatR,
            """
            #nullable enable
            using MediatR;

            namespace Sample.Contracts
            {
                public sealed record RocketModel(System.Guid Id, string Name);
                public readonly struct Unparsable { }
                public static class GetRocket { public sealed record Request(System.Guid Id) : IRequest<RocketModel>; }
                public static class FindRocket { public sealed record Request(System.Guid Id) : IRequest<RocketModel>; }
                public static class SearchRockets { public sealed record Request(Unparsable Filter) : IRequest<RocketModel[]>; }
                public static class CreateRocket
                {
                    public sealed record Request(string Name) : IRequest<Response>;
                    [Rocket.Surgery.LaunchPad.Api.Creates(typeof(FindRocket.Request))] public sealed record Response(System.Guid Id);
                }
            }
            """
        );
        var result = await Server(Mediator.MediatR, contracts)
                          .AddSources($"using Rocket.Surgery.LaunchPad.Api;\nusing Sample.Contracts;\n\n{attributes}\n{declaration}\n")
                          .Build()
                          .GenerateAsync(TestContext.CancellationToken);

        DiagnosticIds(result).ShouldContain(id);
        await Verify(result).UseParameters(id);
    }

    [Test]
    public async Task Should_Report_A_Request_Without_A_Response()
    {
        var contracts = await GeneratorTestContextBuilder
                             .Create()
                             .WithLogger(Logger)
                             .WithAssemblyLoadContext(AssemblyLoadContext)
                             .WithProjectName("Contracts")
                             .AddSources("namespace Sample.Contracts { public static class GetRocket { public sealed record Request(System.Guid Id); } }")
                             .Build()
                             .GenerateAsync(TestContext.CancellationToken);
        var result = await Server(Mediator.MediatR, contracts)
                          .AddSources("using Rocket.Surgery.LaunchPad.Api;\n[Operation<Sample.Contracts.GetRocket.Request>]\npublic static partial class RocketsEndpoints;")
                          .Build()
                          .GenerateAsync(TestContext.CancellationToken);

        DiagnosticIds(result).ShouldContain("LPAD1001");
        await Verify(result);
    }
}
